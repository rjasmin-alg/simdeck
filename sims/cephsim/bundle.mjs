// Bundles js/**/*.js (ES modules that import each other) into app.js, one classic script, because the simdeck build
// inlines only classic scripts and import-free modules (docs/site-structure.md §5). No dependencies: each module
// becomes a function scope whose imports are read from the modules before it and whose exports it returns.
// Adapted from sims/topologydrafter/bundle.mjs: modules live in subfolders (js/engine/), so a module's key is its
// path under js/ without .js ('engine/crush'), and imports resolve relative to the importing file; a dynamic
// import('./x.js') becomes Promise.resolve(<that module>), which is safe because it only runs after boot.
//   node sims/cephsim/bundle.mjs           write app.js
//   node sims/cephsim/bundle.mjs --check   exit 1 when app.js is not what js/ bundles to
// It handles the forms these modules use: named imports from './x.js' or '../x.js' (with `as`), `export
// function|async function|class|const|let`, and `export { a, b };`. Anything else (default exports, `import *`,
// re-exports, bare specifiers) is an error.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const ENTRY = 'main';

/** The key of `spec` imported from module `from` ('engine/crush' importing './hash.js' → 'engine/hash'). */
export function resolve(from, spec) {
  const key = path.posix.normalize(path.posix.join(path.posix.dirname(from), spec)).replace(/\.js$/, '');
  if (key.startsWith('..')) throw new Error(`${from}.js: import ${spec} leaves js/`);
  return key;
}

/** One module's source → { deps, body, exports }. */
export function transform(name, src) {
  const deps = [];
  const exports = [];
  let body = src.replace(/^import\s*\{([^}]*)\}\s*from\s*'(\.{1,2}\/[\w/.-]+\.js)';?[ \t]*$/gm, (_, list, spec) => {
    const dep = resolve(name, spec);
    deps.push(dep);
    const names = list.split(',').map((s) => s.trim()).filter(Boolean)
      .map((s) => s.replace(/^(\w+)\s+as\s+(\w+)$/, '$1: $2'));
    return `const { ${names.join(', ')} } = __mods[${JSON.stringify(dep)}];`;
  });
  // Lazy imports: the module is bundled (it is a static import elsewhere) and boot has finished when these run.
  body = body.replace(/\bimport\(\s*'(\.{1,2}\/[\w/.-]+\.js)'\s*\)/g,
    (_, spec) => `Promise.resolve(__mods[${JSON.stringify(resolve(name, spec))}])`);
  body = body.replace(/^export\s*\{([^}]*)\};?[ \t]*$/gm, (_, list) => {
    exports.push(...list.split(',').map((s) => s.trim()).filter(Boolean));
    return '';
  });
  body = body.replace(/^export\s+((?:async\s+)?function\*?|class|const|let)\s+(\w+)/gm, (_, kw, id) => {
    exports.push(id);
    return `${kw} ${id}`;
  });
  const left = /^\s*(import|export)\b.*$/m.exec(body) || /\bimport\(.*$/m.exec(body);
  if (left) throw new Error(`${name}.js: cannot bundle "${left[0].trim()}"`);
  return { deps, body, exports: [...new Set(exports)] };
}

/** Modules in dependency order (each after everything it imports), from the entry. */
export function order(mods, entry) {
  const out = [];
  const state = new Map();
  const visit = (n, trail) => {
    if (state.get(n) === 'done') return;
    if (state.get(n) === 'busy') throw new Error(`import cycle: ${[...trail, n].join(' → ')}`);
    if (!mods.has(n)) throw new Error(`missing module ${n}.js (from ${trail.at(-1)})`);
    state.set(n, 'busy');
    for (const d of mods.get(n).deps) visit(d, [...trail, n]);
    state.set(n, 'done');
    out.push(n);
  };
  visit(entry, []);
  return out;
}

export function bundle(dir = path.join(here, 'js')) {
  const mods = new Map();
  const load = (n) => {
    if (mods.has(n)) return;
    const m = transform(n, readFileSync(path.join(dir, `${n}.js`), 'utf8'));
    mods.set(n, m);
    m.deps.forEach(load);
  };
  load(ENTRY);
  const names = order(mods, ENTRY);
  const parts = names.map((n) => {
    const m = mods.get(n);
    const wrapped = `__mods[${JSON.stringify(n)}] = (function () {\n${m.body.trimEnd()}\n\nreturn { ${m.exports.join(', ')} };\n})();`;
    // The entry boots the app; sim.test.js loads the bundle without booting (CEPHSIM_NO_BOOT).
    return n === ENTRY ? `if (!globalThis.CEPHSIM_NO_BOOT) {\n${wrapped}\n}` : wrapped;
  });
  return `/* SPDX-License-Identifier: AGPL-3.0-or-later
   GENERATED by bundle.mjs from the modules in js/: do not edit. Change js/ and run node sims/cephsim/bundle.mjs. */
(function () {
'use strict';
var __mods = {};
globalThis.CephSim = { modules: __mods };

// ── ${names.join(' → ')} ──
${parts.join('\n\n')}
})();
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = path.join(here, 'app.js');
  const text = bundle();
  if (process.argv.includes('--check')) {
    const now = readFileSync(out, 'utf8');
    if (now !== text) { console.error('app.js is stale: run node sims/cephsim/bundle.mjs'); process.exit(1); }
    console.log('app.js is up to date');
  } else {
    writeFileSync(out, text);
    console.log(`wrote ${path.relative(process.cwd(), out)} (${(text.length / 1024).toFixed(1)} KB)`);
  }
}
