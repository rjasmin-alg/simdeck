__mods["engine/domain"] = (function () {
// The fault-domain tree: pure containment. geo > region > zone > dc > rack > host > psu.
//
// The tree is the "where" axis and it is the only thing that makes redundancy
// checkable: three replicas are only three replicas if they sit in three
// different domains of the kind you care about. Nothing here knows what a
// region *is* — the kind ladder comes from a profile.

// Membership is a stored field (`component.domain`), never inferred from
// geometry. See CLAUDE.md: a relationship you cannot record is one you cannot
// validate.

function domainIndex(doc) {
  const byId = new Map();
  const children = new Map();
  const roots = [];
  for (const d of doc.domains || []) {
    byId.set(d.id, d);
    if (!children.has(d.id)) children.set(d.id, []);
  }
  for (const d of doc.domains || []) {
    if (d.parent && byId.has(d.parent)) {
      if (!children.has(d.parent)) children.set(d.parent, []);
      children.get(d.parent).push(d.id);
    } else {
      roots.push(d.id);
    }
  }
  return { byId, children, roots };
}

// Root-ward chain, self first. Stops on a cycle rather than hanging: a
// malformed document should give a wrong answer, not a locked tab.
function ancestry(doc, domainId, idx = domainIndex(doc)) {
  const out = [];
  const seen = new Set();
  let cur = domainId;
  while (cur && idx.byId.has(cur) && !seen.has(cur)) {
    seen.add(cur);
    out.push(cur);
    cur = idx.byId.get(cur).parent;
  }
  return out;
}

// Every domain in the subtree, self included.
function descendants(doc, domainId, idx = domainIndex(doc)) {
  const out = [];
  const stack = [domainId];
  const seen = new Set();
  while (stack.length) {
    const id = stack.pop();
    if (seen.has(id) || !idx.byId.has(id)) continue;
    seen.add(id);
    out.push(id);
    for (const c of idx.children.get(id) || []) stack.push(c);
  }
  return out;
}

// Component ids anywhere under a domain.
function componentsIn(doc, domainId, idx = domainIndex(doc)) {
  const under = new Set(descendants(doc, domainId, idx));
  return (doc.components || []).filter((c) => under.has(c.domain)).map((c) => c.id);
}

// The ancestor of `kind` that a component sits under, or null.
function domainOfKind(doc, compId, kind, idx = domainIndex(doc)) {
  const comp = (doc.components || []).find((c) => c.id === compId);
  if (!comp) return null;
  for (const id of ancestry(doc, comp.domain, idx)) {
    if (idx.byId.get(id).kind === kind) return id;
  }
  return null;
}

// How many distinct domains of `kind` these components occupy. This is the
// number that tells you whether "three replicas" means anything: three copies
// with a spread of 1 at rack level is one power strip away from zero copies.
function spread(doc, compIds, kind, idx = domainIndex(doc)) {
  const seen = new Set();
  let unplaced = 0;
  for (const id of compIds) {
    const d = domainOfKind(doc, id, kind, idx);
    if (d) seen.add(d); else unplaced++;
  }
  return { count: seen.size, domains: [...seen], unplaced };
}

// Lowest domain containing all of them — the blast radius of their nearest
// shared ancestor. Returns null when they share nothing (separate roots).
function commonAncestor(doc, compIds, idx = domainIndex(doc)) {
  const chains = [];
  for (const id of compIds) {
    const comp = (doc.components || []).find((c) => c.id === id);
    if (!comp) continue;
    chains.push(ancestry(doc, comp.domain, idx));
  }
  if (!chains.length) return null;
  let candidates = chains[0];
  for (const chain of chains.slice(1)) {
    const set = new Set(chain);
    candidates = candidates.filter((d) => set.has(d));
  }
  return candidates[0] || null;
}

function depth(doc, domainId, idx = domainIndex(doc)) {
  return ancestry(doc, domainId, idx).length;
}

return { domainIndex, ancestry, descendants, componentsIn, domainOfKind, spread, commonAncestor, depth };
})();

__mods["engine/events"] = (function () {
// A failure *event* is the honest unit, not a component.
//
// Nobody loses "server 12". They lose a power strip, a top-of-rack switch, an
// availability zone, a certificate, or a config push — and each of those takes
// out a *set* of components that the diagram drew as independent. This is the
// entire reason redundancy lies: N copies are only N-fold safety if the
// failures are independent, and the interesting ones never are.
//
// So the cut-set search enumerates over events, uniformly. Components and
// domains contribute their own automatic events; authored correlated events sit
// alongside them with no special casing.

const { componentsIn, domainIndex } = __mods["engine/domain"];

const EVENT_KINDS = {
  component:  { id: 'component',  label: 'Component fails' },
  domain:     { id: 'domain',     label: 'Domain lost' },
  correlated: { id: 'correlated', label: 'Correlated event' },
};

function eventUniverse(doc, { domainEvents = true, componentEvents = true } = {}) {
  const idx = domainIndex(doc);
  const out = [];

  if (componentEvents) {
    for (const c of doc.components || []) {
      out.push({
        id: `ev:comp:${c.id}`,
        name: c.name || c.id,
        kind: 'component',
        target: c.id,
        implicit: !!c.implicit,
        hits: new Set([c.id]),
      });
    }
  }

  if (domainEvents) {
    for (const d of doc.domains || []) {
      if (d.implicit) continue; // "Not drawn" is a holder, not a place that can fail
      const hits = componentsIn(doc, d.id, idx);
      if (!hits.length) continue;
      out.push({
        id: `ev:dom:${d.id}`,
        name: `${d.name || d.id} lost`,
        kind: 'domain',
        target: d.id,
        domainKind: d.kind,
        hits: new Set(hits),
      });
    }
  }

  for (const e of doc.events || []) {
    const hits = new Set();
    for (const h of e.hits || []) {
      if (idx.byId.has(h)) for (const c of componentsIn(doc, h, idx)) hits.add(c);
      else hits.add(h);
    }
    if (!hits.size) continue;
    out.push({
      id: `ev:evt:${e.id}`,
      name: e.name || e.id,
      kind: 'correlated',
      target: e.id,
      note: e.note,
      hits,
    });
  }

  return out;
}

// Two events are redundant for search purposes when they hit exactly the same
// set. A rack containing one host and that host are the same failure told twice;
// keeping both only pads the cut list. The survivor is the one with the more
// specific story — a component before a correlated event before a whole domain.
function dedupeUniverse(universe) {
  const bySignature = new Map();
  const rank = { component: 0, correlated: 1, domain: 2 };
  for (const e of universe) {
    const sig = [...e.hits].sort().join(' ');
    const prev = bySignature.get(sig);
    if (!prev || (rank[e.kind] ?? 9) < (rank[prev.kind] ?? 9)) bySignature.set(sig, e);
  }
  return [...bySignature.values()];
}

return { EVENT_KINDS, eventUniverse, dedupeUniverse };
})();

__mods["compile"] = (function () {
// Document -> analysis. The one seam between what the user drew and what the
// engine reasons about.
//
// The implicit authorities are attached *here*, not in the document. That is
// deliberate: they are a property of the analysis, not of the drawing, so they
// cannot be deleted, saved away, or exported out of existence. Modelling one
// means drawing something better, not removing a row.

const { attachAuthorities } = __mods["engine/authorities"];
const { buildGraph } = __mods["engine/graph"];
const { cutSets } = __mods["engine/cutset"];
const { dedupeUniverse, eventUniverse } = __mods["engine/events"];

// Only what can change an answer. Positions, labels and colours are absent, so
// dragging a box costs zero recomputation — the same trick as
// cephsim/js/compile.js:26.
function structuralSignature(doc) {
  const parts = [];
  for (const d of doc.domains || []) parts.push(`d:${d.id}:${d.kind}:${d.parent || ''}`);
  for (const c of doc.components || []) parts.push(`c:${c.id}:${c.role}:${c.domain}:${c.authorityKind || ''}`);
  for (const e of doc.deps || []) parts.push(`e:${e.from}>${e.to}:${e.gate || 'all'}:${e.n ?? ''}:${e.group || ''}`);
  for (const e of doc.events || []) parts.push(`v:${e.id}:${[...(e.hits || [])].sort().join(',')}`);
  parts.push(`s:${doc.settings?.maxCutSize ?? 3}:${doc.settings?.authorities !== false}`);
  return parts.join('|');
}

let cache = { sig: null, value: null, epoch: 0 };

function currentEpoch() {
  return cache.epoch;
}

function invalidate() {
  cache = { sig: null, value: null, epoch: cache.epoch + 1 };
}

function compile(doc) {
  const sig = structuralSignature(doc);
  if (sig === cache.sig && cache.value) return cache.value;

  const withAuth =
    doc.settings?.authorities === false ? { doc, added: [] } : attachAuthorities(doc);
  const expanded = withAuth.doc;
  const graph = buildGraph(expanded);
  const universe = dedupeUniverse(eventUniverse(expanded));

  const value = { doc: expanded, graph, universe, added: withAuth.added, epoch: cache.epoch + 1 };
  cache = { sig, value, epoch: cache.epoch + 1 };
  return value;
}

// The headline, and it is deliberately not a number.
//
// `smallest` and `smallestDrawn` used to be counts, and a count cannot tell the
// two answers a student most needs distinguished apart: `threeZone` is redundant
// right up to the region boundary and reports 1, while a design where one server
// kills the service also reports 1. The size is the least informative part. What
// carries the meaning is how wide the failure is and what *kind* of thing it is —
// a region, a rack, a host, a config push — because that is the unit an operator
// already reasons in.
function describeCut(cut) {
  if (!cut) return null;
  return {
    size: cut.size,
    blastRadius: cut.blastRadius,
    scope: cut.scope,
    drawn: cut.drawn,
    names: cut.events.map((e) => e.name),
  };
}

// Cut sets for every service in the document, plus the headline the UI leans on.
function analyse(doc) {
  const c = compile(doc);
  const maxSize = doc.settings?.maxCutSize ?? 3;
  const services = c.doc.components.filter((x) => x.role === 'service');

  const results = services.map((s) => {
    const r = cutSets(c.graph, s.id, c.universe, { maxSize });
    return {
      service: s,
      ...r,
      drawnCuts: r.cuts.filter((x) => x.drawn),
      implicitCuts: r.cuts.filter((x) => !x.drawn),
      smallest: describeCut(r.cuts[0]),
      smallestDrawn: describeCut(r.cuts.find((x) => x.drawn)),
    };
  });

  return { ...c, services: results };
}

return { structuralSignature, currentEpoch, invalidate, compile, describeCut, analyse };
})();

