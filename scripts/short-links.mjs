#!/usr/bin/env node
// Prints the nginx rules for courses with a short address (materijali.online/<short>), one per course.
// scripts/deploy.sh uploads the output as /etc/nginx/snippets/simdeck-short.conf; the admin shows the same text.
// Usage: node scripts/short-links.mjs [--root <dir>]
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadRepo, validate } from '../lib/manifest.mjs';
import { shortLinkRules } from '../site/core.mjs';

const i = process.argv.indexOf('--root');
const root = i > 0 ? resolve(process.argv[i + 1]) : join(dirname(fileURLToPath(import.meta.url)), '..');
const repo = loadRepo(root);
const { courses, errors } = validate(repo);
if (errors.length) {
  for (const e of errors) console.error(`error: ${e}`);
  process.exit(1);
}
const rules = shortLinkRules(courses, repo.site);
process.stdout.write(`# simdeck: short course addresses. Generated by scripts/short-links.mjs; do not edit.\n${rules ? `${rules}\n` : ''}`);
