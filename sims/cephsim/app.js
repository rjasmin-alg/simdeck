__mods["engine/hash"] = (function () {
// SPDX-License-Identifier: AGPL-3.0-or-later
// Robert Jenkins' hash, exactly as Ceph implements it in src/crush/hash.c.
//
// This one is a faithful port, not an approximation: CRUSH's whole behaviour —
// which OSD a PG lands on, and how little moves when the map changes — comes out
// of this function. Getting it right is what makes the rest trustworthy.
//
// C's __u32 arithmetic maps onto JS cleanly as long as every step is forced back
// into 32 bits. `|0` does that for -, and `>>>` implicitly does ToUint32 on its
// operand, so `c >>> 13` is already the logical shift C would do on a __u32.

const SEED = 1315423911;

/** The 9-step avalanche from crush_hashmix(). Operates on [a, b, c]. */
function mix(s) {
  let [a, b, c] = s;
  a = (a - b) | 0; a = (a - c) | 0; a ^= c >>> 13;
  b = (b - c) | 0; b = (b - a) | 0; b ^= a << 8;
  c = (c - a) | 0; c = (c - b) | 0; c ^= b >>> 13;
  a = (a - b) | 0; a = (a - c) | 0; a ^= c >>> 12;
  b = (b - c) | 0; b = (b - a) | 0; b ^= a << 16;
  c = (c - a) | 0; c = (c - b) | 0; c ^= b >>> 5;
  a = (a - b) | 0; a = (a - c) | 0; a ^= c >>> 3;
  b = (b - c) | 0; b = (b - a) | 0; b ^= a << 10;
  c = (c - a) | 0; c = (c - b) | 0; c ^= b >>> 15;
  s[0] = a; s[1] = b; s[2] = c;
}

function hash1(a) {
  a |= 0;
  let hash = SEED ^ a;
  let b = a, x = 231232, y = 1232;
  let s = [b, x, hash]; mix(s); b = s[0]; x = s[1]; hash = s[2];
  s = [y, a, hash]; mix(s); y = s[0]; a = s[1]; hash = s[2];
  return hash >>> 0;
}

function hash2(a, b) {
  a |= 0; b |= 0;
  let hash = SEED ^ a ^ b;
  let x = 231232, y = 1232;
  let s = [a, b, hash]; mix(s); a = s[0]; b = s[1]; hash = s[2];
  s = [x, a, hash]; mix(s); x = s[0]; a = s[1]; hash = s[2];
  s = [b, y, hash]; mix(s); b = s[0]; y = s[1]; hash = s[2];
  return hash >>> 0;
}

function hash3(a, b, c) {
  a |= 0; b |= 0; c |= 0;
  let hash = SEED ^ a ^ b ^ c;
  let x = 231232, y = 1232;
  let s = [a, b, hash]; mix(s); a = s[0]; b = s[1]; hash = s[2];
  s = [c, x, hash]; mix(s); c = s[0]; x = s[1]; hash = s[2];
  s = [y, a, hash]; mix(s); y = s[0]; a = s[1]; hash = s[2];
  s = [b, x, hash]; mix(s); b = s[0]; x = s[1]; hash = s[2];
  s = [y, c, hash]; mix(s); y = s[0]; c = s[1]; hash = s[2];
  return hash >>> 0;
}

function hash4(a, b, c, d) {
  a |= 0; b |= 0; c |= 0; d |= 0;
  let hash = SEED ^ a ^ b ^ c ^ d;
  let x = 231232, y = 1232;
  let s = [a, b, hash]; mix(s); a = s[0]; b = s[1]; hash = s[2];
  s = [c, d, hash]; mix(s); c = s[0]; d = s[1]; hash = s[2];
  s = [a, x, hash]; mix(s); a = s[0]; x = s[1]; hash = s[2];
  s = [y, b, hash]; mix(s); y = s[0]; b = s[1]; hash = s[2];
  s = [c, x, hash]; mix(s); c = s[0]; x = s[1]; hash = s[2];
  s = [y, d, hash]; mix(s); y = s[0]; d = s[1]; hash = s[2];
  return hash >>> 0;
}

// Ceph's stable PG masking (ceph_stable_mod). Keeps a value inside pg_num even
// when pg_num is not a power of two, and does it in a way that only moves the
// values that had to move when pg_num grows — which is why splitting a pool is
// cheap and why pg_num values that are not powers of two are merely untidy
// rather than broken.
function stableMod(x, b, bmask) {
  return (x & bmask) < b ? (x & bmask) : (x & (bmask >> 1));
}

/**
 * The companion mask: (1 << cbits(n - 1)) - 1, i.e. the smallest 2^k-1 that can
 * hold n-1. pg_num 1 -> 0, 2 -> 1, 100 -> 127, 512 -> 511.
 */
function bmaskFor(n) {
  let m = 0;
  while (m < n - 1) m = (m << 1) | 1;
  return m;
}

return { hash1, hash2, hash3, hash4, stableMod, bmaskFor };
})();

__mods["engine/crush"] = (function () {
// SPDX-License-Identifier: AGPL-3.0-or-later
// The CRUSH engine: straw2 buckets and rule execution.
//
// Ported from Ceph's src/crush/mapper.c. The structure is faithful — recursive
// descent, retry accounting, the firstn/indep split, chooseleaf recursion and
// vary_r — because those details are exactly what a student gets wrong and what
// this tool exists to make visible.
//
// Two documented divergences from upstream (see README "What this is not"):
//   1. straw2 uses Math.log rather than Ceph's fixed-point crush_ln() table.
//      Statistically identical; individual PG->OSD mappings may differ.
//   2. Only straw2 and uniform buckets exist. list/tree buckets were deprecated
//      long before anyone reading this deployed a cluster.

const { hash2, hash3 } = __mods["engine/hash"];

const NONE = 0x7fffffff;   // CRUSH_ITEM_NONE
const UNDEF = 0x7ffffffe;         // CRUSH_ITEM_UNDEF

// The standard type ladder. Index is the numeric type id CRUSH compares against.
const TYPES = [
  'osd', 'host', 'chassis', 'rack', 'row', 'pdu',
  'pod', 'room', 'datacenter', 'zone', 'region', 'root',
];
const typeId = (name) => TYPES.indexOf(name);

// "Optimal" tunables, i.e. what any cluster from Jewel onwards runs.
const DEFAULT_TUNABLES = {
  choose_total_tries: 50,
  choose_local_tries: 0,
  choose_local_fallback_tries: 0,
  chooseleaf_descend_once: 1,
  chooseleaf_vary_r: 1,
  // chooseleaf_stable is deliberately not modelled: it perturbs which leaf a
  // descent settles on to shave a little data movement, and getting it subtly
  // wrong would be worse than not having it. Documented in README.
};

// ------------------------------------------------------------------ buckets --

/**
 * straw2: every child draws a random number scaled by its weight, highest wins.
 * The magic is that a child's draw does not depend on any other child, so
 * removing one child leaves every other child's draw untouched — which is why
 * only that child's share of the data moves.
 */
function straw2Choose(bucket, x, r) {
  let high = -1;
  let highDraw = -Infinity;
  for (let i = 0; i < bucket.items.length; i++) {
    const w = bucket.weights[i];
    let draw;
    if (w > 0) {
      const u = hash3(x, bucket.items[i], r) & 0xffff;
      // ln over (0, 1] — always negative, so a bigger weight means a bigger
      // (less negative) draw. Matches crush_ln()'s [1/0x10000, 1] domain.
      draw = Math.log((u + 1) / 65536) / w;
    } else {
      draw = -Infinity;
    }
    if (high < 0 || draw > highDraw) { high = i; highDraw = draw; }
  }
  return high < 0 ? NONE : bucket.items[high];
}

/**
 * Partial Fisher-Yates over the bucket's items, as crush_bucket_perm_choose
 * does. Ceph memoises the permutation across calls; recomputing it is the same
 * answer, just slower, and uniform buckets are vanishingly rare in practice.
 */
function uniformChoose(bucket, x, r) {
  const size = bucket.items.length;
  if (size === 0) return NONE;
  const pr = ((r % size) + size) % size;
  const perm = [];
  for (let i = 0; i < size; i++) perm.push(i);
  const i0 = hash3(x, bucket.id, 0) % size;
  perm[0] = i0; perm[i0] = 0;
  for (let p = 1; p <= pr; p++) {
    if (p < size - 1) {
      const i = hash3(x, bucket.id, p) % (size - p);
      if (i) { const t = perm[p + i]; perm[p + i] = perm[p]; perm[p] = t; }
    }
  }
  return bucket.items[perm[pr]];
}

function bucketChoose(bucket, x, r) {
  return bucket.alg === 'uniform' ? uniformChoose(bucket, x, r)
                                  : straw2Choose(bucket, x, r);
}

/**
 * `ceph osd reweight` — a probabilistic rejection at selection time, entirely
 * separate from the CRUSH weight in the bucket. An OSD at reweight 0.5 is still
 * full-weight in the tree; it just gets thrown back half the time. This is the
 * distinction people conflate, and it is why reweighting cascades badly.
 */
function isOut(reweights, x, item) {
  const w = reweights[item];
  if (w === undefined) return true;
  const fixed = Math.round(w * 0x10000);
  if (fixed >= 0x10000) return false;
  if (fixed === 0) return true;
  return (hash2(x, item) & 0xffff) >= fixed;
}

// ------------------------------------------------------------------- firstn --

function chooseFirstn(map, bucket, reweights, x, numrep, type, out, outposIn,
                      tries, recurseTries, localRetries, localFallbackRetries,
                      recurseToLeaf, varyR, out2, parentR) {
  let outpos = outposIn;

  for (let rep = outpos; rep < numrep; rep++) {
    let skipRep = false;
    let item = NONE;
    let ftotal = 0;
    let retryDescent = true;

    while (retryDescent) {
      retryDescent = false;
      let inB = bucket;
      let flocal = 0;
      let retryBucket = true;

      while (retryBucket) {
        retryBucket = false;
        let r = rep + parentR + ftotal + flocal;
        item = bucketChoose(inB, x, r);
        if (item === NONE) { skipRep = true; break; }

        const itype = item >= 0 ? 0 : map.buckets[item].typeId;
        if (itype !== type) {
          if (item >= 0 || !map.buckets[item]) { skipRep = true; break; }
          inB = map.buckets[item];
          retryBucket = true;
          continue;
        }

        let collide = false;
        for (let i = 0; i < outpos; i++) if (out[i] === item) { collide = true; break; }

        let reject = false;
        if (!collide && recurseToLeaf) {
          if (item < 0) {
            const subR = varyR ? (r >> (varyR - 1)) : 0;
            const got = chooseFirstn(map, map.buckets[item], reweights, x,
              outpos + 1, 0, out2, outpos,
              recurseTries, recurseTries, localRetries, localFallbackRetries,
              false, varyR, null, subR);
            if (got <= outpos) reject = true;   // descent found no usable leaf
          } else {
            out2[outpos] = item;
          }
        }
        if (!reject && !collide && item >= 0) reject = isOut(reweights, x, item);

        if (reject || collide) {
          ftotal++;
          flocal++;
          if (collide && flocal <= localRetries) retryBucket = true;
          else if (localFallbackRetries > 0 &&
                   flocal <= localRetries + localFallbackRetries) retryBucket = true;
          else if (ftotal < tries) retryDescent = true;
          else skipRep = true;
        }
      }
      if (skipRep) break;
    }

    if (skipRep) continue;
    out[outpos] = item;
    outpos++;
  }
  return outpos;
}

// -------------------------------------------------------------------- indep --

/**
 * The erasure-coded path. Unlike firstn, position matters: shard 3 is shard 3.
 * A shard that cannot be placed leaves a NONE hole rather than shifting the
 * shards after it, because shifting them would invalidate every stripe.
 */
function chooseIndep(map, bucket, reweights, x, left, numrep, type,
                     out, outpos, tries, recurseTries, recurseToLeaf,
                     out2, parentR) {
  const endpos = outpos + left;
  for (let rep = outpos; rep < endpos; rep++) {
    out[rep] = UNDEF;
    if (out2) out2[rep] = UNDEF;
  }

  for (let ftotal = 0; left > 0 && ftotal < tries; ftotal++) {
    for (let rep = outpos; rep < endpos; rep++) {
      if (out[rep] !== UNDEF) continue;
      let inB = bucket;

      for (;;) {
        let r = rep + parentR;
        r += (inB.alg === 'uniform' && inB.items.length % numrep === 0)
          ? (numrep + 1) * ftotal
          : numrep * ftotal;

        const item = bucketChoose(inB, x, r);
        if (item === NONE) {
          out[rep] = NONE;
          if (out2) out2[rep] = NONE;
          left--;
          break;
        }

        const itype = item >= 0 ? 0 : map.buckets[item].typeId;
        if (itype !== type) {
          if (item >= 0 || !map.buckets[item]) {
            out[rep] = NONE;
            if (out2) out2[rep] = NONE;
            left--;
            break;
          }
          inB = map.buckets[item];
          continue;
        }

        let collide = false;
        for (let i = outpos; i < endpos; i++) if (out[i] === item) { collide = true; break; }
        if (collide) break;

        if (recurseToLeaf) {
          if (item < 0) {
            chooseIndep(map, map.buckets[item], reweights, x, 1, numrep, 0,
                        out2, rep, recurseTries, recurseTries, false, null, r);
            if (out2[rep] === NONE) break;
          } else {
            out2[rep] = item;
          }
        }

        if (itype === 0 && isOut(reweights, x, item)) break;

        out[rep] = item;
        left--;
        break;
      }
    }
  }

  for (let rep = outpos; rep < endpos; rep++) {
    if (out[rep] === UNDEF) out[rep] = NONE;
    if (out2 && out2[rep] === UNDEF) out2[rep] = NONE;
  }
}

// ----------------------------------------------------------------- do_rule --

/**
 * Run one CRUSH rule for placement value `x`.
 *
 * @param {object} map        compiled crush map (see buildMap in crushmap.js)
 * @param {string|number} ruleRef  rule id or name
 * @param {number} x          the placement value (a hashed PG id)
 * @param {number} maxOut     replicas / shards wanted (pool size, or k+m)
 * @param {number[]} reweights  osd id -> 0..1 reweight
 * @returns {number[]} osd ids, length <= maxOut, possibly containing NONE
 */
function doRule(map, ruleRef, x, maxOut, reweights) {
  const rule = typeof ruleRef === 'number'
    ? map.rules.find((r) => r.id === ruleRef)
    : map.rules.find((r) => r.name === ruleRef);
  if (!rule) throw new Error(`crush: no such rule ${ruleRef}`);

  const t = map.tunables;
  let w = [];                       // the current working set
  const result = [];
  let recurseTries = t.choose_total_tries;
  let chooseTries = t.choose_total_tries;
  let chooseLeafTries = 0;

  for (const step of rule.steps) {
    switch (step.op) {
      case 'set_choose_tries': chooseTries = step.num; break;
      case 'set_chooseleaf_tries': chooseLeafTries = step.num; break;
      case 'take': {
        const id = map.rootId(step.item, step.class);
        // A take that resolves to nothing is not an error: `take default class
        // nvme` on a cluster with no NVMe has no shadow tree to take, and a real
        // cluster answers by placing nothing. panel-pools.js surfaces it as a
        // pool warning, which is where it is actionable.
        if (id === undefined) { w = []; break; }
        w = [id];
        break;
      }
      case 'choose':
      case 'chooseleaf': {
        const leaf = step.op === 'chooseleaf';
        const type = typeof step.type === 'number' ? step.type : typeId(step.type);
        if (type < 0) throw new Error(`crush: unknown type ${step.type}`);
        const out = [];
        for (const item of w) {
          let numrep = step.num;
          if (numrep <= 0) {
            numrep = maxOut + numrep;
            if (numrep <= 0) continue;
          }
          if (item >= 0) { out.push(item); continue; }   // already a device
          const bucket = map.buckets[item];
          const out2 = leaf ? [] : null;
          const scratch = [];
          if (step.mode === 'indep') {
            chooseIndep(map, bucket, reweights, x, numrep, numrep, type,
                        scratch, 0, chooseTries,
                        chooseLeafTries || recurseTries, leaf, out2, 0);
            const src = leaf ? out2 : scratch;
            for (let i = 0; i < numrep; i++) out.push(src[i] === undefined ? NONE : src[i]);
          } else {
            const n = chooseFirstn(map, bucket, reweights, x, numrep, type,
                        scratch, 0, chooseTries,
                        chooseLeafTries || recurseTries,
                        t.choose_local_tries, t.choose_local_fallback_tries,
                        leaf, t.chooseleaf_vary_r, out2, 0);
            const src = leaf ? out2 : scratch;
            for (let i = 0; i < n; i++) if (src[i] !== undefined) out.push(src[i]);
          }
        }
        w = out;
        break;
      }
      case 'emit':
        for (const item of w) result.push(item);
        w = [];
        break;
      default:
        throw new Error(`crush: unknown rule op ${step.op}`);
    }
  }
  return result.slice(0, maxOut);
}

return { NONE, TYPES, typeId, DEFAULT_TUNABLES, doRule };
})();

__mods["engine/crushmap"] = (function () {
// SPDX-License-Identifier: AGPL-3.0-or-later
// Building and finalising a CRUSH map.
//
// A map is plain data. `finalize()` does the two derivations Ceph does for you
// on a real cluster and that everybody forgets are happening:
//
//   1. Bucket weights are the sum of their children, bottom-up. You never set a
//      rack's weight; it *is* the sum of its hosts.
//   2. Device classes become shadow trees. `default~ssd` is a real, parallel
//      hierarchy containing only the SSDs, and `step take default class ssd`
//      takes that tree. Without this, "put metadata on SSD" cannot work.

const { TYPES, typeId, DEFAULT_TUNABLES } = __mods["engine/crush"];

function newMap(tunables = {}) {
  const map = {
    devices: {},                  // id -> {id, name, class, weight}
    buckets: {},                  // negative id -> bucket
    rules: [],
    tunables: { ...DEFAULT_TUNABLES, ...tunables },
    byName: {},                   // bucket name -> id
    parent: {},                   // child id -> parent bucket id
    nextBucketId: -1,
    shadow: {},                   // "rootName~class" -> shadow bucket id
  };
  map.rootId = (name, cls) => {
    if (cls) {
      const s = map.shadow[`${name}~${cls}`];
      if (s !== undefined) return s;
      return undefined;
    }
    return map.byName[name];
  };
  return map;
}

function addDevice(map, id, name, cls = 'hdd', weight = 1) {
  map.devices[id] = { id, name, class: cls, weight };
  return id;
}

/**
 * `id` may be given to preserve the numbering from an imported crushmap. Ceph
 * itself treats bucket ids as stable identifiers ("do not change unnecessarily"),
 * so honouring them makes a decompile/compile round trip byte-for-byte stable.
 */
function addBucket(map, { name, type, alg = 'straw2', items = [], id: wanted }) {
  const id = wanted !== undefined && wanted !== null ? wanted : map.nextBucketId--;
  if (id <= map.nextBucketId) map.nextBucketId = id - 1;
  map.buckets[id] = {
    id, name, alg,
    typeName: type,
    typeId: typeId(type),
    items: [...items],
    weights: [],
    weight: 0,
    shadowOf: null,
    shadowClass: null,
  };
  map.byName[name] = id;
  return id;
}

function addRule(map, rule) {
  const id = rule.id !== undefined ? rule.id : map.rules.length;
  map.rules.push({ ...rule, id });
  return id;
}

/** Weight of any item, device or bucket. Devices carry theirs; buckets sum. */
function weightOf(map, id) {
  return id >= 0 ? (map.devices[id]?.weight ?? 0) : (map.buckets[id]?.weight ?? 0);
}

/** Post-order so a bucket is only summed after all of its children are. */
function recomputeWeights(map) {
  const seen = new Set();
  const visit = (id) => {
    if (id >= 0 || seen.has(id)) return;
    seen.add(id);
    const b = map.buckets[id];
    if (!b) return;
    for (const it of b.items) visit(it);
    b.weights = b.items.map((it) => weightOf(map, it));
    b.weight = b.weights.reduce((a, x) => a + x, 0);
  };
  for (const id of Object.keys(map.buckets)) visit(Number(id));
}

function recomputeParents(map) {
  map.parent = {};
  for (const id of Object.keys(map.buckets)) {
    const b = map.buckets[id];
    if (b.shadowOf !== null) continue;          // shadows are not real parents
    for (const it of b.items) map.parent[it] = Number(id);
  }
}

/** Every device class appearing under `id`. */
function classesUnder(map, id, acc = new Set()) {
  if (id >= 0) { const d = map.devices[id]; if (d) acc.add(d.class); return acc; }
  const b = map.buckets[id];
  if (b) for (const it of b.items) classesUnder(map, it, acc);
  return acc;
}

/**
 * Mirror `id`'s subtree keeping only devices of `cls`. Returns the new shadow
 * bucket id, or undefined when nothing of that class lives down here — an empty
 * rack simply does not appear in the shadow tree, which is what makes
 * "take default class ssd" skip racks that have no SSDs.
 */
function cloneShadow(map, id, cls) {
  if (id >= 0) return map.devices[id]?.class === cls ? id : undefined;
  const b = map.buckets[id];
  if (!b) return undefined;
  const items = [];
  for (const it of b.items) {
    const c = cloneShadow(map, it, cls);
    if (c !== undefined) items.push(c);
  }
  if (items.length === 0) return undefined;
  const sid = addBucket(map, { name: `${b.name}~${cls}`, type: b.typeName, alg: b.alg, items });
  map.buckets[sid].shadowOf = id;
  map.buckets[sid].shadowClass = cls;
  return sid;
}

function buildShadows(map) {
  // Drop any shadow buckets from a previous finalize.
  for (const id of Object.keys(map.buckets)) {
    const b = map.buckets[id];
    if (b.shadowOf !== null) { delete map.byName[b.name]; delete map.buckets[id]; }
  }
  map.shadow = {};
  for (const id of Object.keys(map.buckets).map(Number)) {
    const b = map.buckets[id];
    if (!b || b.typeName !== 'root') continue;
    for (const cls of classesUnder(map, id)) {
      const sid = cloneShadow(map, id, cls);
      if (sid !== undefined) map.shadow[`${b.name}~${cls}`] = sid;
    }
  }
}

/** Call after any structural change. Idempotent. */
function finalize(map) {
  recomputeParents(map);
  buildShadows(map);
  recomputeWeights(map);
  return map;
}

/** Devices under an item, in tree order. */
function devicesUnder(map, id, acc = []) {
  if (id >= 0) { acc.push(id); return acc; }
  const b = map.buckets[id];
  if (b) for (const it of b.items) devicesUnder(map, it, acc);
  return acc;
}

/** The chain of bucket names from a device up to its root — for `ceph osd tree`. */
function ancestry(map, id) {
  const chain = [];
  let cur = map.parent[id];
  while (cur !== undefined) { chain.push(map.buckets[cur]); cur = map.parent[cur]; }
  return chain;
}

/** Reweight vector (all 1.0) sized for the map's devices. */
function defaultReweights(map) {
  const rw = [];
  for (const id of Object.keys(map.devices)) rw[Number(id)] = 1;
  return rw;
}

return { TYPES, newMap, addDevice, addBucket, addRule, finalize, devicesUnder, ancestry, defaultReweights };
})();

__mods["engine/pgmap"] = (function () {
// SPDX-License-Identifier: AGPL-3.0-or-later
// PGs: the layer between "a pool holds data" and "these disks hold bytes".
//
// A pool is pg_num placement groups. Each PG hashes to a placement value, CRUSH
// turns that into an ordered set of OSDs, and the OSDs that are actually up and
// in become the PG's acting set. Everything a user sees — capacity, degraded
// counts, whether the filesystem still answers — is derived from here.

const { doRule, NONE } = __mods["engine/crush"];
const { hash2, hash3, stableMod, bmaskFor } = __mods["engine/hash"];

/**
 * A PG's placement value, exactly as OSDMap::raw_pg_to_pps computes it with the
 * HASHPSPOOL flag (on by default since Firefly).
 *
 * Note it hashes through pgp_num, not pg_num. That is why raising pg_num alone
 * splits PGs without moving any data, and raising pgp_num is what actually
 * shuffles it — the single most useful thing to know when growing a pool.
 */
function pgToPps(pool, ps) {
  const mask = bmaskFor(pool.pgp_num);
  return hash2(stableMod(ps, pool.pgp_num, mask), pool.id);
}

/** Replicas (replicated) or shards (erasure) a pool wants. */
function poolWidth(pool) {
  return pool.type === 'erasure' ? pool.k + pool.m : pool.size;
}

/** Below this many live shards the PG stops serving I/O. */
function poolMinSize(pool) {
  if (pool.min_size !== undefined) return pool.min_size;
  return pool.type === 'erasure' ? pool.k : Math.max(1, pool.size - 1);
}

/**
 * Raw CRUSH output for every PG in a pool. This is the expensive call — it is
 * the one thing the tick loop must never do. Cache it against a map epoch.
 */
function mapPool(map, pool, reweights) {
  const width = poolWidth(pool);
  const raw = new Array(pool.pg_num);
  for (let ps = 0; ps < pool.pg_num; ps++) {
    raw[ps] = doRule(map, pool.crush_rule, pgToPps(pool, ps), width, reweights);
  }
  return raw;
}

// PG states, named as `ceph pg stat` names them.
const CLEAN = 'active+clean';

/**
 * Turn raw CRUSH output into up/acting sets and a state, given which OSDs are
 * currently down.
 *
 * `out` OSDs never appear here at all — being out is expressed as reweight 0,
 * so CRUSH has already routed around them. `down` OSDs *do* appear in the raw
 * set (CRUSH does not know about liveness) and are subtracted here. That split
 * is real, and it is why marking an OSD down and marking it out do different
 * things.
 */
function pgState(pool, rawSet, down, prevActing) {
  const width = poolWidth(pool);
  const minSize = poolMinSize(pool);
  const holes = rawSet.filter((o) => o === NONE).length;
  const placed = rawSet.filter((o) => o !== NONE);
  const up = placed.filter((o) => !down.has(o));

  const states = [];
  let active = up.length >= minSize;

  if (up.length === 0) {
    states.push('stale', 'inactive');
    active = false;
  } else if (!active) {
    states.push('incomplete', 'inactive');
  } else {
    states.push('active');
  }

  if (active) {
    // `placed` already dropped NONE holes, so a hole shows up here as a short
    // up set — an EC shard CRUSH could not place is degraded from birth.
    if (up.length < width) states.push('undersized', 'degraded');
    if (prevActing && prevActing.length) {
      const moved = up.some((o) => !prevActing.includes(o));
      if (moved) states.push(up.length < width ? 'backfilling' : 'remapped');
    }
    if (states.length === 1) states.push('clean');
  }

  return {
    up,
    acting: up,
    primary: up.length ? up[0] : null,
    holes,
    active,
    degraded: active && up.length < width,
    state: states.join('+'),
  };
}

/** Deterministic per-PG byte size, so the same cluster always fills the same way. */
function pgBytes(pool, ps, total, skew) {
  const base = total / pool.pg_num;
  if (!skew) return base;
  // Box-Muller off the hash, so it is reproducible rather than random.
  const u1 = (hash3(pool.id, ps, 1) >>> 0) / 4294967296 || 1e-9;
  const u2 = (hash3(pool.id, ps, 2) >>> 0) / 4294967296;
  const z = Math.sqrt(-2 * Math.log(u1)) * Math.cos(2 * Math.PI * u2);
  return base * Math.exp(skew * z - (skew * skew) / 2);   // mean-preserving
}

/**
 * Everything derived for one pool: per-PG placement, state counts, and how many
 * bytes each OSD is carrying on this pool's behalf.
 *
 * @param {object} opts.down  Set of down osd ids
 * @param {number} opts.skew  per-PG size variance (0 = every PG identical)
 */
function evaluatePool(map, pool, reweights, opts = {}) {
  const down = opts.down || new Set();
  const skew = opts.skew ?? 0.25;
  const prev = opts.prev || null;
  const raw = opts.raw || mapPool(map, pool, reweights);
  const width = poolWidth(pool);

  const pgs = new Array(pool.pg_num);
  const stateCounts = {};
  const osdBytes = new Map();
  const osdPgs = new Map();
  let degraded = 0, inactive = 0, misplaced = 0, undersizedShards = 0;

  // An EC shard is stored/k bytes; a replica is the whole thing.
  const perShard = pool.type === 'erasure' ? 1 / pool.k : 1;

  for (let ps = 0; ps < pool.pg_num; ps++) {
    const st = pgState(pool, raw[ps], down, prev ? prev[ps] : null);
    pgs[ps] = st;
    stateCounts[st.state] = (stateCounts[st.state] || 0) + 1;
    if (!st.active) inactive++;
    if (st.degraded) { degraded++; undersizedShards += width - st.up.length; }
    if (st.state.includes('remapped') || st.state.includes('backfilling')) misplaced++;

    const bytes = pgBytes(pool, ps, pool.stored || 0, skew) * perShard;
    // Recovery needs this to know how long each shard takes to copy, and there
    // is no point recomputing a distribution we have already drawn.
    st.bytes = bytes;
    for (const o of st.up) {
      osdBytes.set(o, (osdBytes.get(o) || 0) + bytes);
      osdPgs.set(o, (osdPgs.get(o) || 0) + 1);
    }
  }

  return {
    pool, raw, pgs, stateCounts, osdBytes, osdPgs,
    degraded, inactive, misplaced, undersizedShards,
    active: pool.pg_num - inactive,
    /** raw bytes this pool consumes across all OSDs */
    rawUsed: [...osdBytes.values()].reduce((a, b) => a + b, 0),
  };
}

/** Raw-to-usable ratio: 1/size replicated, k/(k+m) erasure. */
function poolEfficiency(pool) {
  return pool.type === 'erasure' ? pool.k / (pool.k + pool.m) : 1 / pool.size;
}

return { NONE, pgToPps, poolWidth, poolMinSize, mapPool, CLEAN, pgState, evaluatePool, poolEfficiency };
})();

__mods["engine/capacity"] = (function () {
// SPDX-License-Identifier: AGPL-3.0-or-later
// Capacity. The part everyone gets wrong on a real cluster.
//
// A Ceph cluster does not have "free space". It has a fullest OSD, and that OSD
// decides when writes stop. `ceph df`'s MAX AVAIL is not total-free/size — it is
// a projection from whichever OSD will hit the full ratio first, given its share
// of the CRUSH weight. A cluster with 400 TB free and one 90%-full OSD has very
// little MAX AVAIL, and that surprise is the reason this module exists.

const { devicesUnder } = __mods["engine/crushmap"];
const { poolEfficiency, poolWidth } = __mods["engine/pgmap"];

const RATIOS = { nearfull: 0.85, backfillfull: 0.90, full: 0.95 };

const TiB = 1024 ** 4;
const GiB = 1024 ** 3;

/** Human byte formatting in the units `ceph df` uses. */
function fmtBytes(b) {
  if (!isFinite(b)) return '-';
  const neg = b < 0; b = Math.abs(b);
  const u = ['B', 'KiB', 'MiB', 'GiB', 'TiB', 'PiB', 'EiB'];
  let i = 0;
  while (b >= 1024 && i < u.length - 1) { b /= 1024; i++; }
  const s = b >= 100 || i === 0 ? b.toFixed(0) : b.toFixed(b >= 10 ? 1 : 2);
  return `${neg ? '-' : ''}${s} ${u[i]}`;
}

/**
 * Per-OSD usage, summed over every pool's contribution.
 *
 * @param {object} map
 * @param {object[]} evals  results from evaluatePool()
 * @returns {Map<number, {used, total, avail, ratio, pgs, class, weight}>}
 */
function osdUsage(map, evals) {
  const usage = new Map();
  for (const id of Object.keys(map.devices).map(Number)) {
    const d = map.devices[id];
    usage.set(id, {
      id, used: 0, pgs: 0,
      total: d.weight * TiB,        // CRUSH weight is TiB by convention
      class: d.class, weight: d.weight,
      avail: d.weight * TiB, ratio: 0,
    });
  }
  for (const ev of evals) {
    for (const [osd, bytes] of ev.osdBytes) {
      const u = usage.get(osd);
      if (u) u.used += bytes;
    }
    for (const [osd, n] of ev.osdPgs) {
      const u = usage.get(osd);
      if (u) u.pgs += n;
    }
  }
  for (const u of usage.values()) {
    u.avail = Math.max(0, u.total - u.used);
    u.ratio = u.total > 0 ? u.used / u.total : 0;
  }
  return usage;
}

/**
 * The normalised weight each OSD contributes to a rule, as
 * crush_get_rule_weight_osd_map does: walk the rule's root, sum device weights,
 * divide through so the shares add to 1.
 */
function ruleWeightMap(map, ruleRef) {
  const rule = typeof ruleRef === 'number'
    ? map.rules.find((r) => r.id === ruleRef)
    : map.rules.find((r) => r.name === ruleRef);
  if (!rule) return new Map();
  const take = rule.steps.find((s) => s.op === 'take');
  if (!take) return new Map();
  const rootId = map.rootId(take.item, take.class);
  if (rootId === undefined) return new Map();

  const wm = new Map();
  let total = 0;
  for (const id of devicesUnder(map, rootId)) {
    const w = map.devices[id]?.weight ?? 0;
    if (w <= 0) continue;
    wm.set(id, w);
    total += w;
  }
  if (total > 0) for (const [k, v] of wm) wm.set(k, v / total);
  return wm;
}

/**
 * Raw bytes still writable through a rule before the first OSD hits the full
 * ratio. Ported from PGMap::get_rule_avail.
 */
function ruleAvail(map, ruleRef, usage, fullRatio = RATIOS.full) {
  const wm = ruleWeightMap(map, ruleRef);
  let min = -1;
  for (const [osd, share] of wm) {
    const u = usage.get(osd);
    if (!u || u.total === 0 || share === 0) continue;
    const headroom = u.total * fullRatio - u.used;
    const proj = headroom / share;
    if (min < 0 || proj < min) min = proj;
  }
  return Math.max(0, min);
}

/** `ceph df` for one pool: what a user can still write into it. */
function poolDf(map, pool, usage, evals) {
  const ev = evals.find((e) => e.pool.id === pool.id);
  const raw = ruleAvail(map, pool.crush_rule, usage);
  return {
    name: pool.name,
    stored: pool.stored || 0,
    used: ev ? ev.rawUsed : 0,                 // raw bytes on disk
    maxAvail: raw * poolEfficiency(pool),      // usable bytes still writable
    efficiency: poolEfficiency(pool),
    width: poolWidth(pool),
  };
}

/** Cluster-wide `ceph df` header plus the fullness warnings. */
function clusterDf(map, usage) {
  let total = 0, used = 0;
  for (const u of usage.values()) { total += u.total; used += u.used; }
  const nearfull = [], backfillfull = [], full = [];
  for (const u of usage.values()) {
    if (u.ratio >= RATIOS.full) full.push(u.id);
    else if (u.ratio >= RATIOS.backfillfull) backfillfull.push(u.id);
    else if (u.ratio >= RATIOS.nearfull) nearfull.push(u.id);
  }
  const ratios = [...usage.values()].map((u) => u.ratio).filter((r) => r > 0);
  const mean = ratios.length ? ratios.reduce((a, b) => a + b, 0) / ratios.length : 0;
  return {
    total, used, avail: total - used,
    ratio: total ? used / total : 0,
    nearfull, backfillfull, full,
    // How lopsided the fill is — the number the balancer exists to shrink.
    spread: ratios.length ? (Math.max(...ratios) - Math.min(...ratios)) : 0,
    stddev: ratios.length
      ? Math.sqrt(ratios.reduce((a, r) => a + (r - mean) ** 2, 0) / ratios.length)
      : 0,
  };
}

return { RATIOS, TiB, GiB, fmtBytes, osdUsage, ruleWeightMap, ruleAvail, poolDf, clusterDf };
})();

__mods["engine/net"] = (function () {
// SPDX-License-Identifier: AGPL-3.0-or-later
// The network, and what losing part of it does to the cluster.
//
// Ceph runs on two networks and people forget it: the **public** network carries
// clients, monitors and heartbeats to the mons, while the **cluster** network
// carries replication and recovery between OSDs. Cutting one is not like cutting
// the other, and that asymmetry is what this file exists to show.
//
// The model, stated plainly so it can be argued with:
//
//   * MONs form quorum over the public network. A majority of *configured* mons
//     must be mutually reachable, or the cluster stops serving entirely — this
//     is the one failure that takes a healthy set of disks completely offline.
//   * An OSD that cannot reach the quorum over the public network is marked
//     down, because that is exactly what the mons do to it.
//   * An OSD that can reach the mons but is cut off from its peers on the
//     cluster network is also marked down: its peers stop seeing heartbeats and
//     report it. On a real cluster this is the flapping scenario; here it
//     settles straight to down, which is the end state rather than the drama.
//
// Simplification worth knowing about: real Ceph needs `mon_osd_min_down_reporters`
// peers to agree before marking an OSD down, and a split cluster network causes
// minutes of flapping first. None of that timing is modelled.

/**
 * Network modelling is only meaningful once cables exist. A document with no
 * links at all has simply not described its network, so everything is treated as
 * connected; a *cabled* cluster is modelled properly.
 *
 * A host with no cables in an otherwise cabled document is likewise treated as
 * "network not drawn" rather than isolated — otherwise a half-finished diagram
 * reports a dead cluster, which is alarming and wrong.
 */
function networkState(doc) {
  const enabled = doc.links.length > 0;
  const hosts = doc.hosts;
  const nodeUp = new Map();
  for (const h of hosts) nodeUp.set(h.id, h.up !== false);
  for (const s of doc.switches) nodeUp.set(s.id, s.up !== false);

  const liveLinks = doc.links.filter((l) =>
    l.up !== false && nodeUp.get(l.a) && nodeUp.get(l.b));

  const cabled = new Set();
  for (const l of doc.links) { cabled.add(l.a); cabled.add(l.b); }

  const pub = components(liveLinks.filter((l) => l.net !== 'cluster'), nodeUp);
  const clu = components(liveLinks.filter((l) => l.net === 'cluster'), nodeUp);
  const hasClusterNet = doc.links.some((l) => l.net === 'cluster');

  // ------------------------------------------------------------ quorum ------
  const monHosts = hosts.filter((h) => h.daemons.includes('mon'));
  const needed = Math.floor(monHosts.length / 2) + 1;
  const upMons = monHosts.filter((h) => h.up !== false);

  let quorumComponent = null;
  let inQuorum = [];
  let largestGroup = 0;
  if (monHosts.length === 0) {
    // No mons at all: nothing to lose, so do not pretend the cluster is down.
    quorumComponent = null;
    inQuorum = [];
  } else if (!enabled) {
    inQuorum = upMons.length >= needed ? upMons : [];
    largestGroup = upMons.length;
    if (upMons.length < needed) quorumComponent = undefined;
  } else {
    const groups = new Map();
    for (const h of upMons) {
      const c = comp(pub, h.id, cabled);
      if (!groups.has(c)) groups.set(c, []);
      groups.get(c).push(h);
    }
    let best = null;
    for (const [c, list] of groups) {
      largestGroup = Math.max(largestGroup, list.length);
      if (list.length >= needed && (!best || list.length > best[1].length)) best = [c, list];
    }
    if (best) { [quorumComponent, inQuorum] = best; }
    else { quorumComponent = undefined; inQuorum = []; }
  }
  const hasQuorum = monHosts.length === 0 || inQuorum.length >= needed;

  // ------------------------------------------- which hosts can serve --------
  const unreachable = new Set();
  const reasons = new Map();
  if (!hasQuorum && monHosts.length > 0) {
    for (const h of hosts) {
      unreachable.add(h.id);
      reasons.set(h.id, 'no monitor quorum');
    }
  } else if (enabled && quorumComponent !== null && quorumComponent !== undefined) {
    for (const h of hosts) {
      if (h.up === false || !cabled.has(h.id)) continue;
      if (comp(pub, h.id, cabled) !== quorumComponent) {
        unreachable.add(h.id);
        reasons.set(h.id, 'cut off from the monitors on the public network');
        continue;
      }
      if (hasClusterNet && cabledOn(doc, h.id, 'cluster')) {
        // Cut off from its peers: the peers stop hearing it and report it down.
        const peers = hosts.filter((o) => o.id !== h.id && o.up !== false
          && o.osds.length && cabledOn(doc, o.id, 'cluster'));
        const mine = comp(clu, h.id, cabled);
        if (peers.length && !peers.some((o) => comp(clu, o.id, cabled) === mine)) {
          unreachable.add(h.id);
          reasons.set(h.id, 'isolated from its peers on the cluster network');
        }
      }
    }
  }

  return {
    enabled,
    hasClusterNet,
    cabled,
    uncabled: new Set(hosts.filter((h) => !cabled.has(h.id)).map((h) => h.id)),
    publicComponents: pub,
    clusterComponents: clu,
    quorum: {
      configured: monHosts.length,
      up: upMons.length,
      needed,
      inQuorum: inQuorum.map((h) => h.id),
      hasQuorum,
      /** The biggest set of mons that can actually see each other. */
      largestGroup,
      /**
       * Enough monitors are alive to form a quorum, but they cannot reach each
       * other. That is a genuinely different failure from "too many mons are
       * down", and the fix is different too — repair the network, not the mons.
       */
      partitioned: !hasQuorum && monHosts.length > 0 && upMons.length >= needed,
    },
    unreachableHosts: unreachable,
    reasons,
  };
}

/** Union-find over one network's live links. Returns node id -> component id. */
function components(links, nodeUp) {
  const parent = new Map();
  const find = (x) => {
    if (!parent.has(x)) parent.set(x, x);
    while (parent.get(x) !== x) { parent.set(x, parent.get(parent.get(x))); x = parent.get(x); }
    return x;
  };
  const union = (a, b) => { const ra = find(a), rb = find(b); if (ra !== rb) parent.set(ra, rb); };
  for (const l of links) { if (nodeUp.get(l.a) && nodeUp.get(l.b)) union(l.a, l.b); }
  const out = new Map();
  for (const k of parent.keys()) out.set(k, find(k));
  return out;
}

/** A node with no live link of this kind is its own island, keyed by its id. */
function comp(map, id, cabled) {
  return map.has(id) ? map.get(id) : (cabled.has(id) ? `solo:${id}` : 'unmodelled');
}
function cabledOn(doc, nodeId, net) {
  return doc.links.some((l) => l.net === net && (l.a === nodeId || l.b === nodeId));
}

/**
 * Recovery bandwidth available to a host, in bytes per second.
 *
 * Replication and backfill ride the cluster network when there is one and the
 * public network otherwise — which is itself a lesson: without a cluster
 * network, recovery competes with your clients.
 */
function hostBandwidth(doc, hostId) {
  const net = doc.links.some((l) => l.net === 'cluster') ? 'cluster' : 'public';
  const gbps = doc.links
    .filter((l) => l.up !== false && l.net === net && (l.a === hostId || l.b === hostId))
    .reduce((a, l) => a + (l.speed || 0), 0);
  return (gbps * 1e9) / 8;                    // Gb/s -> bytes/s
}

return { networkState, hostBandwidth };
})();

__mods["engine/daemons"] = (function () {
// SPDX-License-Identifier: AGPL-3.0-or-later
// Daemon availability. OSDs hold the data; these decide whether you can get at it.

/**
 * @param {object} doc
 * @param {object} net  result of networkState()
 */
function daemonState(doc, net) {
  const reachable = (h) => h.up !== false && !net.unreachableHosts.has(h.id);
  const on = (id) => doc.hosts.filter((h) => h.daemons.includes(id));
  const upOn = (id) => on(id).filter(reachable);

  const mons = on('mon');
  const mgrs = upOn('mgr');
  const mdss = upOn('mds');
  const rgws = upOn('rgw');

  // CephFS needs at least one MDS rank served. Standbys are the rest.
  const filesystems = (doc.fs || []).map((fs) => {
    const ranks = Math.max(1, fs.maxMds || 1);
    const active = Math.min(mdss.length, ranks);
    return {
      ...fs,
      ranksWanted: ranks,
      ranksActive: active,
      standbys: Math.max(0, mdss.length - active),
      up: active >= 1,
      degraded: active < ranks,
    };
  });

  return {
    mon: {
      configured: mons.length,
      up: mons.filter(reachable).length,
      quorum: net.quorum,
    },
    // MGR is active/standby: one runs, the rest wait. Losing all of them costs
    // you stats, the dashboard and the balancer, but not your data.
    mgr: { configured: on('mgr').length, up: mgrs.length, active: mgrs.length ? 1 : 0,
           standbys: Math.max(0, mgrs.length - 1) },
    mds: { configured: on('mds').length, up: mdss.length },
    rgw: { configured: on('rgw').length, up: rgws.length },
    filesystems,
    /** RGW is stateless, so the endpoint is up if any gateway is. */
    objectGatewayUp: rgws.length > 0,
  };
}

return { daemonState };
})();

__mods["engine/health"] = (function () {
// SPDX-License-Identifier: AGPL-3.0-or-later
// `ceph health detail`, assembled.
//
// Check names are Ceph's real ones, so that what you learn here is what you will
// grep for at three in the morning. Where something is not modelled it simply
// does not appear — there are no invented check names in this list.
//
// Not modelled, and therefore never reported: scrub errors, slow ops, clock
// skew, OSDMAP flags, BlueStore warnings, cephx, device health.

const { RATIOS } = __mods["engine/capacity"];
const { poolWidth, poolMinSize } = __mods["engine/pgmap"];

const OK = 'HEALTH_OK';
const WARN = 'HEALTH_WARN';
const ERR = 'HEALTH_ERR';

// Ceph's own defaults for the PG-per-OSD warnings.
const MIN_PG_PER_OSD = 30;
const MAX_PG_PER_OSD = 250;

function clusterHealth(doc, { net, daemons, evals, usage, df }) {
  const checks = [];
  const add = (name, severity, summary, detail = []) =>
    checks.push({ name, severity, summary, detail });

  // ------------------------------------------------------------- monitors --
  const q = net.quorum;
  if (q.configured === 0) {
    if (doc.hosts.length) {
      add('MON_DOWN', WARN, 'no monitors configured',
        ['A cluster with no monitors has no map and no quorum. Add MON to a host.']);
    }
  } else if (!q.hasQuorum) {
    add('MON_DOWN', ERR,
      q.partitioned
        ? `monitors have lost quorum: ${q.largestGroup} of ${q.configured} can see each other, ${q.needed} needed`
        : `${q.configured - q.up} of ${q.configured} monitors down, quorum needs ${q.needed}`,
      [q.partitioned
        ? 'Enough monitors are running, but the network has split them. The cluster '
          + 'serves no I/O at all until they can reach each other again.'
        : 'Without a majority of monitors the cluster serves no I/O at all, however '
          + 'healthy the disks are.']);
  } else if (q.up < q.configured) {
    add('MON_DOWN', WARN, `${q.configured - q.up} of ${q.configured} monitors down`,
      [`Quorum holds with ${q.largestGroup}; ${q.needed} are needed.`]);
  } else if (q.configured % 2 === 0 && q.configured > 0) {
    add('MON_DOWN', WARN, `${q.configured} monitors is an even number`,
      [`${q.configured} mons tolerate the same ${q.configured / 2 - 1} failures as `
       + `${q.configured - 1} would. Use an odd number.`]);
  }

  // -------------------------------------------------------------- manager --
  if (daemons.mgr.configured === 0 && doc.hosts.length) {
    add('MGR_DOWN', WARN, 'no manager configured',
      ['No stats, no dashboard and no balancer. Data is unaffected.']);
  } else if (daemons.mgr.up === 0 && daemons.mgr.configured > 0) {
    add('MGR_DOWN', WARN, 'no active manager',
      ['Stats, the dashboard and the balancer stop. Data is unaffected.']);
  }

  // -------------------------------------------------------------- OSDs -----
  const allOsds = doc.hosts.flatMap((h) => h.osds.map((o) => ({ o, h })));
  const down = allOsds.filter(({ o, h }) =>
    o.up === false || h.up === false || net.unreachableHosts.has(h.id));
  const out = allOsds.filter(({ o }) => o.in === false);
  if (down.length) {
    const hosts = [...new Set(down.map(({ h }) => h.id))];
    const whole = hosts.filter((id) => {
      const h = doc.hosts.find((x) => x.id === id);
      return h.osds.length && h.osds.every((o) =>
        down.some((d) => d.o.id === o.id));
    });
    add('OSD_DOWN', WARN, `${down.length} osds down`,
      down.slice(0, 8).map(({ o, h }) =>
        `osd.${o.id} (${h.name}) — ${net.reasons.get(h.id) || (h.up === false ? 'host is down' : 'marked down')}`));
    if (whole.length) {
      add('OSD_HOST_DOWN', WARN, `${whole.length} host${whole.length === 1 ? '' : 's'} (${down.length} osds) down`,
        whole.map((id) => {
          const h = doc.hosts.find((x) => x.id === id);
          return `${h.name} — ${net.reasons.get(id) || 'down'}`;
        }));
    }
  }
  if (out.length) {
    add('OSD_OUT', WARN, `${out.length} osds out`,
      out.slice(0, 8).map(({ o, h }) => `osd.${o.id} (${h.name}) reweight 0`));
  }

  // ------------------------------------------------------------ fullness ---
  const named = (ids) => ids.slice(0, 8).map((id) => {
    const u = usage.get(id);
    return `osd.${id} is ${(u.ratio * 100).toFixed(1)}% full`;
  });
  if (df.full.length) {
    add('OSD_FULL', ERR, `${df.full.length} osds full`,
      [...named(df.full), `Writes stop at ${RATIOS.full * 100}%.`]);
  }
  if (df.backfillfull.length) {
    add('OSD_BACKFILLFULL', WARN, `${df.backfillfull.length} osds backfillfull`,
      [...named(df.backfillfull), `Backfill into these stops at ${RATIOS.backfillfull * 100}%.`]);
  }
  if (df.nearfull.length) {
    add('OSD_NEARFULL', WARN, `${df.nearfull.length} osds nearfull`,
      [...named(df.nearfull),
       'A cluster is as full as its fullest OSD, not as full as its average.']);
  }

  // ----------------------------------------------------------------- PGs ---
  let inactive = 0, degraded = 0, undersized = 0, misplaced = 0, totalPgs = 0;
  const availDetail = [], degradedDetail = [];
  for (const ev of evals) {
    totalPgs += ev.pool.pg_num;
    inactive += ev.inactive;
    degraded += ev.degraded;
    misplaced += ev.misplaced;
    undersized += ev.undersizedShards;
    if (ev.inactive) {
      availDetail.push(`pool ${ev.pool.name}: ${ev.inactive} pgs below min_size `
        + `${poolMinSize(ev.pool)} of ${poolWidth(ev.pool)}`);
    }
    if (ev.degraded) degradedDetail.push(`pool ${ev.pool.name}: ${ev.degraded} pgs degraded`);
  }
  if (inactive) {
    add('PG_AVAILABILITY', ERR, `Reduced data availability: ${inactive} pgs inactive`,
      [...availDetail, 'Clients block on these PGs; this is an outage, not a warning.']);
  }
  if (degraded) {
    add('PG_DEGRADED', WARN,
      `Degraded data redundancy: ${undersized} objects degraded, ${degraded} pgs degraded`,
      degradedDetail);
  }
  if (misplaced) {
    add('OBJECT_MISPLACED', WARN, `${misplaced} pgs misplaced`,
      ['Data is safe but not where CRUSH now wants it; backfill will move it.']);
  }

  // --------------------------------------------------------- pool sizing ---
  const inOsds = allOsds.filter(({ o }) => o.in !== false).length;
  if (inOsds > 0 && totalPgs > 0) {
    const replicas = evals.reduce((a, ev) => a + ev.pool.pg_num * poolWidth(ev.pool), 0);
    const per = replicas / inOsds;
    if (per < MIN_PG_PER_OSD) {
      add('TOO_FEW_PGS', WARN, `too few pgs per osd (${per.toFixed(0)} < min ${MIN_PG_PER_OSD})`,
        ['Fewer PGs means coarser placement and a lumpier distribution.']);
    } else if (per > MAX_PG_PER_OSD) {
      add('TOO_MANY_PGS', WARN, `too many pgs per osd (${per.toFixed(0)} > max ${MAX_PG_PER_OSD})`,
        ['Every PG costs memory and peering time on every OSD that holds it.']);
    }
  }
  // Deliberately absent: a check for pgp_num < pg_num. Ceph has no health check
  // for it (the autoscaler owns that now), and inventing one would break the
  // promise that every name here is one you can grep for. panel-pools.js reports
  // it as our own warning instead, where it is clearly ours.

  // -------------------------------------------------------------- CephFS ---
  for (const fs of daemons.filesystems) {
    if (!fs.up) {
      add('MDS_ALL_DOWN', ERR, `filesystem ${fs.name} has no active MDS`,
        ['The filesystem is offline. RADOS below it is unaffected.']);
    } else if (fs.degraded) {
      add('FS_DEGRADED', WARN,
        `filesystem ${fs.name} is degraded: ${fs.ranksActive} of ${fs.ranksWanted} ranks active`, []);
    } else if (fs.standbys === 0) {
      add('MDS_INSUFFICIENT_STANDBY', WARN, `filesystem ${fs.name} has no standby MDS`,
        ['Losing the active MDS takes the filesystem down until one is started.']);
    }
  }

  const status = checks.some((c) => c.severity === ERR) ? ERR
    : checks.length ? WARN : OK;
  return { status, checks, summary: summarise(status, checks) };
}

function summarise(status, checks) {
  if (status === OK) return 'HEALTH_OK';
  return `${status}: ${checks.map((c) => c.summary).join('; ')}`;
}

return { OK, WARN, ERR, clusterHealth };
})();

__mods["engine/clients"] = (function () {
// SPDX-License-Identifier: AGPL-3.0-or-later
// What a user actually touches: a filesystem, a block device, an S3 endpoint.
//
// None of these store anything themselves. Each is a view over one or two RADOS
// pools plus the daemons that front it, and that is the point worth teaching:
// when CephFS goes read-only it is nearly always the pool underneath or the MDS
// in front, not "CephFS" as a thing.
//
// Data volume is deliberately a single number per client, as asked for — a
// percentage or an amount, not simulated objects.

const { poolDf, fmtBytes } = __mods["engine/capacity"];
const { poolWidth, poolMinSize } = __mods["engine/pgmap"];

const poolByName = (doc, name) => doc.pools.find((p) => p.name === name);

/** A pool is serving if none of its PGs are below min_size. */
function poolStatus(evals, pool) {
  if (!pool) return { ok: false, why: 'pool does not exist' };
  const ev = evals.find((e) => e.pool.id === pool.id);
  if (!ev) return { ok: false, why: 'pool has not been evaluated' };
  if (ev.inactive) {
    return { ok: false, why: `${ev.inactive} of ${ev.pool.pg_num} pgs below min_size ${poolMinSize(pool)}` };
  }
  if (ev.degraded) return { ok: true, degraded: true, why: `${ev.degraded} pgs degraded` };
  return { ok: true, degraded: false, why: '' };
}

function clientState(doc, { map, evals, usage, daemons }) {
  const df = (pool) => (pool ? poolDf(map, pool, usage, evals) : null);

  // ------------------------------------------------------------- CephFS ----
  const filesystems = (doc.fs || []).map((fs) => {
    const data = poolByName(doc, fs.dataPool);
    const meta = poolByName(doc, fs.metaPool);
    const dataSt = poolStatus(evals, data);
    const metaSt = poolStatus(evals, meta);
    const mds = daemons.filesystems.find((f) => f.id === fs.id)
      || { up: daemons.mds.up > 0, ranksActive: Math.min(1, daemons.mds.up),
           ranksWanted: fs.maxMds || 1, standbys: Math.max(0, daemons.mds.up - 1) };
    const reasons = [];
    if (!mds.up) reasons.push('no active MDS');
    if (!metaSt.ok) reasons.push(`metadata pool: ${metaSt.why}`);
    if (!dataSt.ok) reasons.push(`data pool: ${dataSt.why}`);
    return {
      ...fs, kind: 'cephfs',
      up: mds.up && metaSt.ok && dataSt.ok,
      degraded: dataSt.degraded || metaSt.degraded || mds.ranksActive < mds.ranksWanted,
      reasons,
      used: data?.stored || 0,
      free: df(data)?.maxAvail ?? 0,
      capacity: (data?.stored || 0) + (df(data)?.maxAvail ?? 0),
      mds,
    };
  });

  // ---------------------------------------------------------------- RBD ----
  const rbd = (doc.rbd || []).map((img) => {
    const pool = poolByName(doc, img.pool);
    const st = poolStatus(evals, pool);
    return {
      ...img, kind: 'rbd',
      up: st.ok,
      degraded: !!st.degraded,
      reasons: st.ok ? [] : [`pool ${img.pool}: ${st.why}`],
      provisioned: img.provisioned || 0,
      used: img.thin ? (img.used || 0) : (img.provisioned || 0),
      free: df(pool)?.maxAvail ?? 0,
    };
  });

  // ---------------------------------------------------------------- RGW ----
  const rgw = (doc.rgw || []).map((gw) => {
    const data = poolByName(doc, gw.dataPool);
    const index = poolByName(doc, gw.indexPool);
    const dataSt = poolStatus(evals, data);
    const indexSt = poolStatus(evals, index);
    const reasons = [];
    if (!daemons.objectGatewayUp) reasons.push('no radosgw running');
    if (!indexSt.ok) reasons.push(`index pool: ${indexSt.why}`);
    if (!dataSt.ok) reasons.push(`data pool: ${dataSt.why}`);
    return {
      ...gw, kind: 'rgw',
      up: daemons.objectGatewayUp && dataSt.ok && indexSt.ok,
      degraded: dataSt.degraded || indexSt.degraded,
      reasons,
      used: data?.stored || 0,
      free: df(data)?.maxAvail ?? 0,
      buckets: gw.buckets || 0,
    };
  });

  // RBD is the one place a user can promise more than exists, so say so.
  const overcommit = [];
  for (const pool of doc.pools) {
    const imgs = rbd.filter((i) => i.pool === pool.name);
    if (!imgs.length) continue;
    const provisioned = imgs.reduce((a, i) => a + i.provisioned, 0);
    const d = df(pool);
    const capacity = (pool.stored || 0) + (d?.maxAvail ?? 0);
    if (provisioned > capacity) {
      overcommit.push({
        pool: pool.name, provisioned, capacity,
        ratio: capacity ? provisioned / capacity : Infinity,
      });
    }
  }

  return { filesystems, rbd, rgw, overcommit };
}

/** Pools a client layer depends on — used to warn before deleting one. */
function poolConsumers(doc, poolName) {
  const out = [];
  for (const fs of doc.fs || []) {
    if (fs.dataPool === poolName) out.push(`${fs.name} (data)`);
    if (fs.metaPool === poolName) out.push(`${fs.name} (metadata)`);
  }
  for (const img of doc.rbd || []) if (img.pool === poolName) out.push(`${img.name} (rbd)`);
  for (const gw of doc.rgw || []) {
    if (gw.dataPool === poolName) out.push(`${gw.name} (rgw data)`);
    if (gw.indexPool === poolName) out.push(`${gw.name} (rgw index)`);
  }
  return out;
}

return { fmtBytes, clientState, poolConsumers };
})();

__mods["compile"] = (function () {
// SPDX-License-Identifier: AGPL-3.0-or-later
// The bridge from the editable document to the pure engine.
//
// The document is what the UI edits: hosts at x/y, OSDs with a size in TiB,
// rules described as "root + class + failure domain". The engine wants a CRUSH
// map. This file translates, and — importantly — decides when a retranslation
// is actually needed.
//
// Remapping is the expensive operation (~90 ms at teaching scale). It is keyed
// off a structural signature, so dragging a host around the canvas, renaming
// something for a slide or scrubbing the recovery clock all cost nothing.

const { newMap, addDevice, addBucket, addRule, finalize, devicesUnder } = __mods["engine/crushmap"];
const { evaluatePool, mapPool } = __mods["engine/pgmap"];
const { osdUsage, clusterDf } = __mods["engine/capacity"];
const { networkState } = __mods["engine/net"];
const { daemonState } = __mods["engine/daemons"];
const { clusterHealth } = __mods["engine/health"];
const { clientState } = __mods["engine/clients"];

/**
 * Everything that can change placement, and nothing that cannot. Position,
 * colour and free-text labels are deliberately absent — that is the whole point.
 */
function structuralSignature(doc) {
  const parts = [];
  for (const b of doc.buckets) parts.push(`b:${b.id}:${b.name}:${b.type}:${b.parent}`);
  for (const h of doc.hosts) {
    parts.push(`h:${h.id}:${h.name}:${h.parent}`);
    for (const o of h.osds) parts.push(`o:${o.id}:${o.size}:${o.class}:${o.in}:${o.reweight}`);
  }
  for (const r of doc.rules) {
    parts.push(`r:${r.id}:${r.name}:${r.root}:${r.class}:${r.failureDomain}:${r.mode}:${
      r.steps ? JSON.stringify(r.steps) : ''}`);
  }
  for (const p of doc.pools) {
    parts.push(`p:${p.id}:${p.type}:${p.size}:${p.k}:${p.m}:${p.pg_num}:${p.pgp_num}:${p.crush_rule}`);
  }
  return parts.join('|');
}

/** A rule as the UI describes it becomes the steps CRUSH actually runs. */
function ruleSteps(rule) {
  if (rule.steps) return rule.steps;
  const mode = rule.mode || (rule.type === 'erasure' ? 'indep' : 'firstn');
  return [
    { op: 'take', item: rule.root || 'default', class: rule.class || null },
    { op: 'chooseleaf', mode, num: 0, type: rule.failureDomain || 'host' },
    { op: 'emit' },
  ];
}

/** Document -> engine CRUSH map. */
function compileMap(doc) {
  const map = newMap();
  const bucketIds = new Map();          // doc bucket id -> engine bucket id

  // Buckets first, deepest last, so a parent always exists before its children
  // are attached. The doc stores the tree by parent pointer; CRUSH wants item
  // lists, so invert it here.
  const children = new Map();
  for (const b of doc.buckets) {
    if (!children.has(b.parent)) children.set(b.parent, []);
    children.get(b.parent).push(b);
  }
  // Parent before children, so ids come out the way Ceph numbers them: the root
  // is -1 and the tree descends from there. Cosmetic, but `ceph osd tree` output
  // that starts at -13 does not look like a real cluster.
  const makeBucket = (b) => {
    const id = addBucket(map, { name: b.name, type: b.type });
    for (const c of children.get(b.id) || []) map.buckets[id].items.push(makeBucket(c));
    for (const h of doc.hosts.filter((x) => x.parent === b.id)) {
      map.buckets[id].items.push(makeHost(h));
    }
    return id;
  };
  const makeHost = (h) => {
    const id = addBucket(map, { name: h.name, type: 'host' });
    for (const o of h.osds) {
      // An OSD marked `out` keeps its CRUSH weight; being out is a reweight of
      // zero, not a weight of zero. Conflating them is the classic mistake and
      // it moves far more data than intended.
      addDevice(map, o.id, `osd.${o.id}`, o.class, o.size);
      map.buckets[id].items.push(o.id);
    }
    return id;
  };

  for (const b of doc.buckets) {
    if (b.parent === null) bucketIds.set(b.id, makeBucket(b));
  }
  // Hosts parented straight to nothing would vanish; park them under the first
  // root so a half-drawn cluster still renders.
  const rootDoc = doc.buckets.find((b) => b.type === 'root');
  const rootEngine = rootDoc ? map.byName[rootDoc.name] : undefined;
  if (rootEngine !== undefined) {
    for (const h of doc.hosts) {
      if (!doc.buckets.some((b) => b.id === h.parent)) {
        map.buckets[rootEngine].items.push(makeHost(h));
      }
    }
  }

  for (const r of doc.rules) {
    addRule(map, { id: r.id, name: r.name, type: r.type, steps: ruleSteps(r) });
  }
  return finalize(map);
}

/**
 * The reweight vector CRUSH consults. `out` is reweight 0 — that is literally
 * how Ceph expresses it, and why an out OSD disappears from acting sets while a
 * down one does not.
 */
function reweightsFor(doc) {
  const rw = [];
  for (const h of doc.hosts) {
    for (const o of h.osds) rw[o.id] = o.in === false ? 0 : (o.reweight ?? 1);
  }
  return rw;
}

/**
 * OSDs that cannot serve. A down host takes its OSDs with it; an explicitly
 * downed OSD counts on its own. Reachability (Phase 4) folds in here too.
 */
function downSet(doc, extra = new Set(), unreachableHosts = new Set()) {
  const down = new Set(extra);
  for (const h of doc.hosts) {
    const hostDown = h.up === false || unreachableHosts.has(h.id);
    for (const o of h.osds) if (hostDown || o.up === false) down.add(o.id);
  }
  return down;
}

// ------------------------------------------------------------------ cache ---
// One remap per structural change, reused until the shape actually moves.
let cache = { sig: null, map: null, raw: new Map(), epoch: 0 };

function currentEpoch() { return cache.epoch; }

function getMap(doc) {
  const sig = structuralSignature(doc);
  if (sig !== cache.sig) {
    cache = { sig, map: compileMap(doc), raw: new Map(), epoch: cache.epoch + 1 };
  }
  return cache.map;
}

/** Raw CRUSH output for a pool, cached against the current map epoch. */
function getRaw(doc, pool, reweights) {
  const map = getMap(doc);
  const key = `${pool.id}:${pool.pg_num}:${pool.pgp_num}:${pool.crush_rule}`;
  if (!cache.raw.has(key)) cache.raw.set(key, mapPool(map, pool, reweights));
  return cache.raw.get(key);
}

/** Drop the memo — for tests, and after a reweight, which CRUSH does consult. */
function invalidate() { cache = { sig: null, map: null, raw: new Map(), epoch: cache.epoch + 1 }; }

/**
 * The whole derived picture for a document, in the order the pieces depend on
 * each other: network first (it decides who is reachable), then placement, then
 * capacity, then health on top of all of it.
 *
 * @param {Set<number>} opts.downOsds  OSDs the user has explicitly marked down,
 *   over and above whatever the topology and the network imply.
 */
function evaluate(doc, { downOsds = new Set(), prev = null } = {}) {
  const map = getMap(doc);
  const reweights = reweightsFor(doc);
  const net = networkState(doc);
  const down = downSet(doc, downOsds, net.unreachableHosts);
  const evals = doc.pools.map((pool) => evaluatePool(map, pool, reweights, {
    down,
    skew: doc.settings?.skew ?? 0.25,
    raw: getRaw(doc, pool, reweights),
    prev: prev?.find((e) => e.pool.id === pool.id)?.pgs.map((p) => p.up) ?? null,
  }));
  const usage = osdUsage(map, evals);
  const df = clusterDf(map, usage);
  const daemons = daemonState(doc, net);
  const health = clusterHealth(doc, { net, daemons, evals, usage, df });
  const clients = clientState(doc, { map, evals, usage, daemons });
  return { map, reweights, net, daemons, evals, usage, df, health, clients, down,
           epoch: cache.epoch };
}

return { devicesUnder, structuralSignature, ruleSteps, compileMap, reweightsFor, downSet, currentEpoch, getMap, getRaw, invalidate, evaluate };
})();

