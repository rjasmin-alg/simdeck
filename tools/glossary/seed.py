"""Seed kit/glossary.js, the shared term list (English term, Croatian term), from the course sources.

  seed.py [--projects ~/projects] [--out kit/glossary.js]

Sources, in priority order (the first source to name an English term wins; later ones are reported):
  ossimulator             docs/POJMOVNIK.md, tables "| EN | HR | status |"
  uvod-u-linux            meta/glossary.yaml, language_note "engleski *<term>* u zagradi"
  uvod-u-racunalne-mreze  meta/terminology-lock.yaml, rows with `english:`

Entries in the existing kit/glossary.js whose "src" is not one of these sources (e.g. "simdeck", added from a
sim's NOTES.md) are kept, so a re-seed never drops hand-added terms. A source row is skipped when its pair
does not split cleanly, or when the book says the Croatian name is not a translation of the English word.
Needs PyYAML (python3-yaml); the generated file needs nothing.
"""
import argparse, json, re, sys
from pathlib import Path

import yaml

SEEDED = ("ossimulator", "uvod-u-linux", "uvod-u-racunalne-mreze")


def clean(s):
    s = re.sub(r"\*|`", "", s).strip()
    return re.sub(r"\s+", " ", s)


def pojmovnik(path):
    """Rows of the EN/HR tables. "a; b | x; y" splits into pairs when both sides have as many parts."""
    out, skipped = [], []
    for line in path.read_text().splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) < 3 or not line.startswith("|") or set(cells[0]) <= set("-: ") or cells[0] in ("EN", "EN (kurzivom u sučelju)"):
            continue
        en, hr = clean(cells[0]), clean(cells[1])
        if hr.startswith("—") or en == "same" or not hr:
            skipped.append(f"ossimulator: {en!r} (no Croatian term)")
            continue
        hr = re.sub(r"\s*\((?:Ts|Tr|Tr/Ts)\)", "", hr)
        ens, hrs = [x.strip() for x in en.split(";")], [x.strip() for x in hr.split(";")]
        if len(ens) != len(hrs):
            skipped.append(f"ossimulator: {en!r} | {hr!r} (parts do not pair)")
            continue
        out += [(e, h) for e, h in zip(ens, hrs) if e and h]
    return out, skipped


def linux_book(path):
    out, skipped = [], []
    for t in yaml.safe_load(path.read_text())["terms"]:
        note = t.get("language_note") or ""
        m = re.search(r"engleski \*([^*]+)\*", note)
        if not m:
            continue
        if "NIJE PRIJEVOD" in note:
            skipped.append(f"uvod-u-linux: {m.group(1)!r} (book: the Croatian name {t['term']!r} is not its translation)")
            continue
        out.append((clean(m.group(1)), clean(t["term"])))
    return out, skipped


def network_book(path):
    out = []
    for t in yaml.safe_load(path.read_text())["terms"]:
        if t.get("english"):
            out.append((clean(str(t["english"])), clean(t["name"])))
    return out, []


def existing(path):
    if not path.exists():
        return []
    m = re.search(r"/\* BEGIN \*/\s*(\[[\s\S]*\])\s*/\* END \*/", path.read_text())
    return json.loads(m.group(1)) if m else []


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--projects", default=str(Path.home() / "projects"))
    ap.add_argument("--out", default=str(Path(__file__).resolve().parents[2] / "kit" / "glossary.js"))
    a = ap.parse_args()
    p, out = Path(a.projects), Path(a.out)

    entries, seen, notes = [], {}, []
    def add(en, hr, src):
        key = en.lower()
        if key in seen:
            if seen[key]["hr"] != hr:
                notes.append(f"{src}: {en!r} = {hr!r}; kept {seen[key]['hr']!r} from {seen[key]['src']}")
            return
        e = {"en": en, "hr": hr, "src": src}
        seen[key] = e
        entries.append(e)

    for e in existing(out):
        if e.get("src") not in SEEDED:
            add(e["en"], e["hr"], e["src"])
    for src, fn, rel in [("ossimulator", pojmovnik, "ossimulator/docs/POJMOVNIK.md"),
                         ("uvod-u-linux", linux_book, "uvod-u-linux/meta/glossary.yaml"),
                         ("uvod-u-racunalne-mreze", network_book, "uvod-u-racunalne-mreze/meta/terminology-lock.yaml")]:
        path = p / rel
        if not path.exists():
            sys.exit(f"missing source: {path}")
        rows, skipped = fn(path)
        notes += skipped
        for en, hr in rows:
            add(en, hr, src)

    body = ",\n".join("  " + json.dumps(e, ensure_ascii=False) for e in entries)
    out.write_text(f"""/* SPDX-License-Identifier: AGPL-3.0-or-later
   simdeck glossary: English term, Croatian term, source. Generated by tools/glossary/seed.py from ossimulator's
   docs/POJMOVNIK.md and the course books' term lists; entries with another "src" (e.g. "simdeck") are hand-added and
   survive a re-seed. A page that uses [[term]] markers links this file after kit.js (docs/sim-ui.md §9). */
(function (root) {{
  'use strict';
  var terms = /* BEGIN */ [
{body}
] /* END */;
  if (typeof module === 'object' && module.exports) module.exports = terms;
  else if (root.Simdeck && root.Simdeck.defineGlossary) root.Simdeck.defineGlossary(terms);
}})(typeof globalThis !== 'undefined' ? globalThis : this);
""")
    print(f"{len(entries)} terms -> {out}")
    for n in notes:
        print(f"  note: {n}")


if __name__ == "__main__":
    main()
