// Regenerates ../placement.js: the raw CRUSH output (size 3, `chooseleaf firstn 0 type host`) for every PG of the two
// pools this sim draws, computed with the cephsim engine (sims/cephsim/js/engine, copied into simdeck from
// ~/projects/cephsim). A size-2 pool takes the first two OSDs of each set: firstn output is prefix-stable, and this
// script checks that it is. Run from the repo root:  node sims/ceph-min-size/tools/gen-placement.mjs
// Dev tool only: the page never loads it.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const eng = join(here, '../../cephsim/js');
const { compileMap, reweightsFor } = await import(join(eng, 'compile.js'));
const { mapPool } = await import(join(eng, 'engine/pgmap.js'));

// cephsim samples.js `hyperconverged`: 3 hosts × 4 OSDs of 4 TiB, rule replicated_rule (host), pool 1 cephfs_data,
// 128 PGs. Built here rather than imported, so the strings of the cephsim page are not needed.
function hc() {
  const hosts = [0, 1, 2].map((i) => ({ id: 'h' + i, name: `ceph-0${i + 1}`, parent: 'root',
    osds: [0, 1, 2, 3].map((k) => ({ id: i * 4 + k, size: 4, class: 'ssd', in: true, reweight: 1 })) }));
  return { hosts, pool: { id: 1, name: 'cephfs_data', type: 'replicated', pg_num: 128, pgp_num: 128, crush_rule: 'replicated_rule' } };
}
// DR estate (student side): configs/hq/hqc/ceph-osd-tree.txt and crushmap.txt; pool 2 vm-rbd, 512 PGs, rule 0
// replicated_rule (take default, chooseleaf firstn 0 type host: every class). osd.22 is down and out (reweight 0).
function dr() {
  const H = 7.27739, S = 1.74660, S2 = 3.49309, B = 10.91409;
  const spec = [
    [[0, H, 'hdd'], [1, H, 'hdd'], [2, H, 'hdd'], [3, H, 'hdd'], [4, H, 'hdd'], [5, S, 'ssd']],
    [[6, H, 'hdd'], [7, H, 'hdd'], [8, H, 'hdd'], [9, H, 'hdd'], [10, H, 'hdd'], [11, S, 'ssd']],
    [[12, H, 'hdd'], [13, S2, 'ssd'], [14, H, 'hdd'], [15, H, 'hdd'], [16, H, 'hdd'], [17, S, 'ssd']],
    [[18, B, 'hdd'], [19, B, 'hdd'], [20, B, 'hdd'], [21, B, 'hdd'], [22, B, 'hdd'], [23, S, 'ssd']],
    [[24, B, 'hdd'], [25, B, 'hdd'], [26, B, 'hdd'], [27, B, 'hdd'], [28, B, 'hdd'], [29, S, 'ssd']],
  ];
  const hosts = spec.map((os, i) => ({ id: 'h' + i, name: `hq-pve-0${i + 1}`, parent: 'root',
    osds: os.map(([id, size, cls]) => ({ id, size, class: cls, in: id !== 22, reweight: id === 22 ? 0 : 1 })) }));
  return { hosts, pool: { id: 2, name: 'vm-rbd', type: 'replicated', pg_num: 512, pgp_num: 512, crush_rule: 'replicated_rule' } };
}

function raw({ hosts, pool }) {
  const doc = { buckets: [{ id: 'root', name: 'default', type: 'root', parent: null }], hosts,
    rules: [{ id: 0, name: 'replicated_rule', type: 'replicated', root: 'default', class: null, failureDomain: 'host', mode: 'firstn' }],
    pools: [pool] };
  const map = compileMap(doc), rw = reweightsFor(doc);
  const r3 = mapPool(map, { ...pool, size: 3 }, rw), r2 = mapPool(map, { ...pool, size: 2 }, rw);
  r2.forEach((s, i) => { if (s[0] !== r3[i][0] || s[1] !== r3[i][1]) throw new Error(`not prefix-stable at PG ${i}`); });
  return r3.map((s) => s.join(',')).join(' ');
}

const out = `/* SPDX-License-Identifier: AGPL-3.0-or-later
   Generated by tools/gen-placement.mjs from the cephsim engine (sims/cephsim/js/engine): do not edit by hand.
   Raw CRUSH output, size 3, one "a,b,c" OSD list per PG in PG order; a size-2 pool uses the first two (firstn is
   prefix-stable). hc: cephsim sample hyperconverged, pool 1 (128 PGs). dr: DR estate hq cluster, pool 2 vm-rbd
   (512 PGs). */
(function (root) {
  'use strict';
  var placement = {
    hc: '${raw(hc())}',
    dr: '${raw(dr())}'
  };
  if (typeof module === 'object' && module.exports) module.exports = placement;
  else root.SimPlacement = placement;
})(typeof globalThis !== 'undefined' ? globalThis : this);
`;
writeFileSync(join(here, '../placement.js'), out);
console.log('wrote placement.js');
