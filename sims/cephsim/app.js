__mods["crushtext"] = (function () {
// SPDX-License-Identifier: AGPL-3.0-or-later
// The real crushtool text format, both directions.
//
// This is the format `ceph osd getcrushmap | crushtool -d -` produces and
// `crushtool -c | ceph osd setcrushmap` consumes. Supporting it is what turns
// this from a toy into something you can point at your actual cluster: paste a
// decompiled map in, see the tree, break it, see what happens.
//
// Shadow buckets (`default~hdd`) ARE emitted, because a class rule is
// meaningless without them on a real cluster. On import they are discarded and
// regenerated by finalize(), so a round trip is stable either way.

const { TYPES, typeId, DEFAULT_TUNABLES } = __mods["engine/crush"];
const { newMap, addDevice, addBucket, addRule, finalize } = __mods["engine/crushmap"];

const w5 = (n) => n.toFixed(5);

// ------------------------------------------------------------- decompile ----
function decompile(map) {
  const out = [];
  out.push('# begin crush map');
  for (const [k, v] of Object.entries(map.tunables)) out.push(`tunable ${k} ${v}`);
  out.push('');

  out.push('# devices');
  for (const id of Object.keys(map.devices).map(Number).sort((a, b) => a - b)) {
    const d = map.devices[id];
    out.push(`device ${id} ${d.name}${d.class ? ` class ${d.class}` : ''}`);
  }
  out.push('');

  out.push('# types');
  TYPES.forEach((t, i) => out.push(`type ${i} ${t}`));
  out.push('');

  out.push('# buckets');
  // Deepest first, exactly as crushtool writes it: a bucket must be defined
  // before anything that lists it as an item.
  for (const b of bucketsByDepth(map)) {
    out.push(`${b.typeName} ${b.name} {`);
    out.push(`\tid ${b.id}\t\t# do not change unnecessarily`);
    out.push(`\t# weight ${w5(b.weight)}`);
    out.push(`\talg ${b.alg}`);
    out.push('\thash 0\t# rjenkins1');
    b.items.forEach((it, i) => {
      const name = it >= 0 ? map.devices[it].name : map.buckets[it].name;
      out.push(`\titem ${name} weight ${w5(b.weights[i] ?? 0)}`);
    });
    out.push('}');
  }
  out.push('');

  out.push('# rules');
  for (const r of map.rules) {
    out.push(`rule ${r.name} {`);
    out.push(`\tid ${r.id}`);
    out.push(`\ttype ${r.type}`);
    for (const s of r.steps) {
      if (s.op === 'take') {
        out.push(`\tstep take ${s.item}${s.class ? ` class ${s.class}` : ''}`);
      } else if (s.op === 'choose' || s.op === 'chooseleaf') {
        out.push(`\tstep ${s.op} ${s.mode} ${s.num} type ${s.type}`);
      } else if (s.op === 'emit') {
        out.push('\tstep emit');
      } else {
        out.push(`\tstep ${s.op} ${s.num}`);
      }
    }
    out.push('}');
  }
  out.push('');
  out.push('# end crush map');
  return out.join('\n');
}

/** Leaf-most buckets first, so every item is already defined when referenced. */
function bucketsByDepth(map) {
  const all = Object.values(map.buckets);
  const depth = new Map();
  const of = (id, seen = new Set()) => {
    if (id >= 0) return 0;
    if (depth.has(id)) return depth.get(id);
    if (seen.has(id)) return 0;                 // a cycle should not hang the export
    seen.add(id);
    const b = map.buckets[id];
    const d = b.items.length ? 1 + Math.max(...b.items.map((i) => of(i, seen))) : 1;
    depth.set(id, d);
    return d;
  };
  return all.sort((a, b) => of(a.id) - of(b.id) || b.id - a.id);
}

// --------------------------------------------------------------- compile ----
class ParseError extends Error {
  constructor(line, n, msg) { super(`line ${n}: ${msg}\n  ${line.trim()}`); }
}

/**
 * Parse crushtool text into the pieces a map is built from. Tolerant about
 * whitespace and comments, strict about anything that would change meaning.
 */
function parseCrushText(text) {
  const devices = [];
  const buckets = [];
  const rules = [];
  const types = new Map();
  const tunables = {};

  const lines = text.split(/\r?\n/);
  let i = 0;
  const strip = (l) => l.replace(/#.*$/, '').trim();

  while (i < lines.length) {
    const raw = lines[i];
    const line = strip(raw);
    i++;
    if (!line) continue;
    const t = line.split(/\s+/);

    if (t[0] === 'tunable') { tunables[t[1]] = Number(t[2]); continue; }
    if (t[0] === 'type') { types.set(Number(t[1]), t[2]); continue; }
    if (t[0] === 'device') {
      const cls = t.indexOf('class');
      devices.push({
        id: Number(t[1]), name: t[2],
        class: cls > 0 ? t[cls + 1] : 'hdd',
      });
      continue;
    }
    if (t[0] === 'rule') {
      const rule = { name: t[1], id: rules.length, type: 'replicated', steps: [] };
      while (i < lines.length && !strip(lines[i]).startsWith('}')) {
        const s = strip(lines[i]); i++;
        if (!s) continue;
        const p = s.split(/\s+/);
        if (p[0] === 'id') rule.id = Number(p[1]);
        else if (p[0] === 'type') rule.type = p[1];
        else if (p[0] === 'step') rule.steps.push(parseStep(p.slice(1), lines[i - 1], i));
        else if (p[0] === 'min_size' || p[0] === 'max_size') { /* pre-Nautilus, ignored */ }
      }
      i++;                                       // consume the closing brace
      rules.push(rule);
      continue;
    }
    // Anything else with a brace is a bucket: `<type> <name> {`
    if (line.endsWith('{')) {
      const bucket = { typeName: t[0], name: t[1], id: null, alg: 'straw2', items: [] };
      while (i < lines.length && !strip(lines[i]).startsWith('}')) {
        const s = strip(lines[i]); i++;
        if (!s) continue;
        const p = s.split(/\s+/);
        // A real bucket carries one bare `id`, then one `id N class X` per
        // device class for its shadow twin. Only the bare one is this bucket's;
        // the shadow ids are regenerated by finalize().
        if (p[0] === 'id' && !p.includes('class')) bucket.id = Number(p[1]);
        else if (p[0] === 'id') { /* shadow bucket id, derived */ }
        else if (p[0] === 'alg') bucket.alg = p[1];
        else if (p[0] === 'hash') { /* rjenkins1 is the only hash we implement */ }
        else if (p[0] === 'item') {
          const wIdx = p.indexOf('weight');
          bucket.items.push({ name: p[1], weight: wIdx > 0 ? Number(p[wIdx + 1]) : null });
        }
      }
      i++;
      if (!bucket.typeName) throw new ParseError(raw, i, 'bucket has no type');
      buckets.push(bucket);
      continue;
    }
    throw new ParseError(raw, i, `did not understand "${t[0]}"`);
  }

  if (!devices.length) throw new Error('no devices in the map');
  if (!buckets.length) throw new Error('no buckets in the map');
  return { devices, buckets, rules, types, tunables };
}

function parseStep(p, raw, n) {
  if (p[0] === 'take') {
    const cls = p.indexOf('class');
    return { op: 'take', item: p[1], class: cls > 0 ? p[cls + 1] : null };
  }
  if (p[0] === 'emit') return { op: 'emit' };
  if (p[0] === 'choose' || p[0] === 'chooseleaf') {
    if (p[1] !== 'firstn' && p[1] !== 'indep') throw new ParseError(raw, n, `bad mode "${p[1]}"`);
    const ti = p.indexOf('type');
    if (ti < 0) throw new ParseError(raw, n, 'choose step has no type');
    return { op: p[0], mode: p[1], num: Number(p[2]), type: p[ti + 1] };
  }
  if (p[0].startsWith('set_')) return { op: p[0], num: Number(p[1]) };
  throw new ParseError(raw, n, `unknown step "${p[0]}"`);
}

/** Parsed text -> engine map. Shadow buckets are dropped and regenerated. */
function compileText(text) {
  const parsed = parseCrushText(text);
  const map = newMap(parsed.tunables);
  const byName = new Map();

  for (const d of parsed.devices) {
    addDevice(map, d.id, d.name, d.class, 0);
    byName.set(d.name, d.id);
  }

  // Real buckets only; `name~class` trees are derived, so importing them would
  // just duplicate what finalize() is about to build.
  const real = parsed.buckets.filter((b) => !b.name.includes('~'));
  // Two passes: create every bucket, then attach items, so order does not matter.
  for (const b of real) {
    if (!TYPES.includes(b.typeName)) throw new Error(`unknown bucket type "${b.typeName}"`);
    byName.set(b.name, addBucket(map, {
      name: b.name, type: b.typeName, alg: b.alg, id: b.id,
    }));
  }
  for (const b of real) {
    const id = byName.get(b.name);
    for (const it of b.items) {
      if (it.name.includes('~')) continue;
      const target = byName.get(it.name);
      if (target === undefined) throw new Error(`bucket ${b.name} lists unknown item ${it.name}`);
      map.buckets[id].items.push(target);
      // A device's weight lives on the device; take it from whoever lists it.
      if (target >= 0 && it.weight !== null) map.devices[target].weight = it.weight;
    }
  }

  for (const r of parsed.rules) addRule(map, r);
  return finalize(map);
}

// ------------------------------------------------------ text -> document ----
/**
 * Build an editable document from a crushmap, laying hosts out by their parent
 * bucket so the canvas is readable straight away. There is no position or
 * network information in a crushmap, so both are invented; everything that
 * affects placement comes from the file.
 */
function docFromCrushText(text, title = 'Imported crushmap') {
  const map = compileText(text);
  const buckets = [];
  const hosts = [];
  const idFor = new Map();
  let n = 0;
  const docId = (p) => `${p}${(n += 1).toString(36)}`;

  for (const b of Object.values(map.buckets)) {
    if (b.shadowOf !== null || b.typeName === 'host') continue;
    const did = docId('bk');
    idFor.set(b.id, did);
    buckets.push({ id: did, name: b.name, type: b.typeName, parent: null });
  }
  for (const b of Object.values(map.buckets)) {
    if (b.shadowOf !== null) continue;
    for (const it of b.items) {
      if (it >= 0 || !idFor.has(it)) continue;
      const child = buckets.find((x) => x.id === idFor.get(it));
      if (child) child.parent = idFor.get(b.id);
    }
  }
  if (!buckets.some((b) => b.type === 'root')) {
    buckets.unshift({ id: docId('bk'), name: 'default', type: 'root', parent: null });
  }

  // Lay hosts out in rows, one row per parent bucket.
  const rows = new Map();
  for (const b of Object.values(map.buckets)) {
    if (b.shadowOf !== null || b.typeName !== 'host') continue;
    const parentEngine = map.parent[b.id];
    const parent = idFor.get(parentEngine) ?? buckets.find((x) => x.type === 'root').id;
    if (!rows.has(parent)) rows.set(parent, []);
    rows.get(parent).push(b);
  }
  let row = 0;
  for (const [parent, list] of rows) {
    list.forEach((b, i) => {
      hosts.push({
        id: docId('h'), name: b.name, x: 40 + i * 260, y: 60 + row * 300,
        parent, up: true, daemons: [],
        osds: b.items.filter((it) => it >= 0).map((it) => ({
          id: it, size: map.devices[it].weight, class: map.devices[it].class,
          up: true, in: true, reweight: 1,
        })),
      });
    });
    row++;
  }

  return {
    version: 1, title,
    buckets, hosts, switches: [], links: [],
    rules: map.rules.map((r) => ({ ...r, steps: r.steps })),
    pools: [], fs: [], rbd: [], rgw: [],
    settings: { skew: 0.25, publicSpeed: 25, clusterSpeed: 25, maxBackfills: 1, recoveryFraction: 0.5 },
  };
}

return { decompile, parseCrushText, compileText, docFromCrushText };
})();

