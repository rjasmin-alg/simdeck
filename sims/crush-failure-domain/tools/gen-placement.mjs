// Regenerates ../placement.js: the raw CRUSH output for every PG of the two pools this sim draws, under both rules
// (`chooseleaf firstn|indep 0 type host` and `type rack`), computed with the cephsim engine (sims/cephsim/js/engine,
// copied into simdeck from ~/projects/cephsim) on cephsim's own sample clusters (js/samples.js `brokenRule` and
// `threeRacks`). It also prints the state counts cephsim's evaluatePool gives with each rack down, which SPEC.md and
// sim.test.js quote. Run from the repo root:  node sims/crush-failure-domain/tools/gen-placement.mjs
// Dev tool only: the page never loads it.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const eng = join(here, '../../cephsim/js');
const { makeSample } = await import(join(eng, 'samples.js'));
const { compileMap, reweightsFor } = await import(join(eng, 'compile.js'));
const { mapPool, evaluatePool, NONE } = await import(join(eng, 'engine/pgmap.js'));

// The hardware is cephsim's threeRacks: 3 racks × 3 hosts × 12 OSDs (osd.0–107, 36 per rack, 12 per host, in order).
const broken = makeSample('brokenRule');           // pool 1 rbd, replicated 3/2, 2048 PGs, rule replicated_rule (host)
const three = makeSample('threeRacks');            // pool 3 cephfs_data, EC 4+2, min_size 4, 1024 PGs, rule ec-host
broken.hosts.forEach((h, i) => h.osds.forEach((o, k) => {
  if (o.id !== i * 12 + k) throw new Error('OSD numbering differs from the model');
}));

const rule = (fd, mode) => ({ id: 0, name: 'r', type: mode === 'indep' ? 'erasure' : 'replicated', root: 'default',
  class: null, failureDomain: fd, mode });
const rackDown = (d, r) => new Set(d.hosts.slice(r * 3, r * 3 + 3).flatMap((h) => h.osds.map((o) => o.id)));

function run(doc, pool, fd, mode) {
  const d = { ...doc, rules: [rule(fd, mode)] };
  const p = { ...pool, crush_rule: 0 };
  const map = compileMap(d), rw = reweightsFor(d);
  const raw = mapPool(map, p, rw);
  for (const r of [0, 1, 2]) {
    const ev = evaluatePool(map, p, rw, { down: rackDown(d, r) });
    console.log(`${pool.name} ${fd} min_size ${p.min_size}, rack${r + 1} down:`, JSON.stringify(ev.stateCounts));
  }
  console.log(`${pool.name} ${fd}, nothing down:`, JSON.stringify(evaluatePool(map, p, rw, {}).stateCounts));
  return raw.map((s) => s.map((o) => (o === NONE ? '-' : o)).join(',')).join(' ');
}

const rbd = broken.pools[0];
const ec = three.pools.find((p) => p.name === 'cephfs_data');
const out = {
  'rbd-host': run(broken, rbd, 'host', 'firstn'),
  'rbd-rack': run(broken, rbd, 'rack', 'firstn'),
  'ec-host': run(three, ec, 'host', 'indep'),
  'ec-rack': run(three, ec, 'rack', 'indep'),
};
run(three, { ...ec, min_size: 5 }, 'host', 'indep');

const js = `/* SPDX-License-Identifier: AGPL-3.0-or-later
   Generated by tools/gen-placement.mjs from the cephsim engine (sims/cephsim/js/engine) on cephsim's samples
   brokenRule / threeRacks: do not edit by hand. Raw CRUSH output, one "a,b,c" OSD list per PG in PG order ("-" is a
   hole, CRUSH_ITEM_NONE). rbd: pool 1, replicated size 3, 2048 PGs, chooseleaf firstn 0 type host | rack.
   ec: pool 3 cephfs_data, erasure 4+2, 1024 PGs, chooseleaf indep 0 type host | rack. */
(function (root) {
  'use strict';
  var placement = {
${Object.entries(out).map(([k, v]) => `    '${k}': '${v}'`).join(',\n')}
  };
  if (typeof module === 'object' && module.exports) module.exports = placement;
  else root.SimPlacement = placement;
})(typeof globalThis !== 'undefined' ? globalThis : this);
`;
writeFileSync(join(here, '../placement.js'), js);
console.log('wrote placement.js');
