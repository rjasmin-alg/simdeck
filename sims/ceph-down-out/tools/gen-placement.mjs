// Regenerates ../placement.js: the raw CRUSH output (size 3, `chooseleaf firstn 0 type host`) for every PG of
// cephsim's `hyperconverged` sample, twice: with every OSD in, and with osd.0 out (reweight 0). Computed with the
// cephsim engine in sims/cephsim/js/engine (copied into simdeck from ~/projects/cephsim). The in-set equals
// sims/ceph-min-size/placement.js `hc` (this script checks it). Run from the repo root:
//   node sims/ceph-down-out/tools/gen-placement.mjs
// Dev tool only: the page never loads it.
import { writeFileSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const eng = join(here, '../../cephsim/js');
const { compileMap, reweightsFor } = await import(join(eng, 'compile.js'));
const { mapPool } = await import(join(eng, 'engine/pgmap.js'));

// cephsim samples.js `hyperconverged`: 3 hosts × 4 OSDs of 4 TiB, rule replicated_rule (host), pool 1 cephfs_data,
// 128 PGs. `outOsd` gets reweight 0 (marked out): CRUSH rejects it and picks again.
function doc(outOsd) {
  const hosts = [0, 1, 2].map((i) => ({ id: 'h' + i, name: `ceph-0${i + 1}`, parent: 'root',
    osds: [0, 1, 2, 3].map((k) => {
      const id = i * 4 + k;
      return { id, size: 4, class: 'ssd', in: id !== outOsd, reweight: id === outOsd ? 0 : 1 };
    }) }));
  const pool = { id: 1, name: 'cephfs_data', type: 'replicated', pg_num: 128, pgp_num: 128, crush_rule: 'replicated_rule', size: 3 };
  return { buckets: [{ id: 'root', name: 'default', type: 'root', parent: null }], hosts,
    rules: [{ id: 0, name: 'replicated_rule', type: 'replicated', root: 'default', class: null, failureDomain: 'host', mode: 'firstn' }],
    pools: [pool] };
}
function raw(d) { return mapPool(compileMap(d), d.pools[0], reweightsFor(d)).map((s) => s.join(',')).join(' '); }

const all = raw(doc(-1)), out0 = raw(doc(0));
const minSize = readFileSync(join(here, '../../ceph-min-size/placement.js'), 'utf8').match(/hc: '([^']+)'/)[1];
if (minSize !== all) throw new Error('in-set differs from sims/ceph-min-size/placement.js hc');

const out = `/* SPDX-License-Identifier: AGPL-3.0-or-later
   Generated by tools/gen-placement.mjs from the cephsim engine (sims/cephsim/js/engine): do not edit by hand.
   Raw CRUSH output for cephsim's hyperconverged sample, pool 1 (128 PGs), size 3, one "a,b,c" OSD list per PG in PG
   order. in: every OSD in (the same as sims/ceph-min-size/placement.js hc). out0: osd.0 out (reweight 0). */
(function (root) {
  'use strict';
  var placement = {
    in: '${all}',
    out0: '${out0}'
  };
  if (typeof module === 'object' && module.exports) module.exports = placement;
  else root.SimPlacement = placement;
})(typeof globalThis !== 'undefined' ? globalThis : this);
`;
writeFileSync(join(here, '../placement.js'), out);
console.log('wrote placement.js');
